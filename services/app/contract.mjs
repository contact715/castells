/*
  КОНТРАКТ: форма данных, в которой пульт отдаёт состояние наружу.

  Зачем отдельным файлом, а не внутри сервера. Форма данных живёт дольше и
  меняется реже, чем транспорт. Пока она сидела внутри web/http.mjs,
  получалось, что описание «как выглядят наши данные» принадлежит модулю
  «как мы отвечаем на HTTP» — и любой второй выход (файл, очередь, другой
  сервер) начал бы описывать ту же форму заново.

  ОДИН ВХОД ДЛЯ ВСЕХ. Правило STACK.md §6: любой потребитель — страница,
  агент, будущий Next.js, телефон — получает данные ТОЛЬКО отсюда, через
  /api/*. Никто не читает профили с диска напрямую. Сегодня это стоит ноль,
  потому что адрес уже есть; завтра именно это делает замену фронта дешёвой.

  ПОЧЕМУ У КОНТРАКТА ЕСТЬ НОМЕР. Как только его начнут читать агенты,
  переименование поля становится поломкой у чужого кода. Номер даёт
  читающему возможность заметить смену формы, а не ловить её по пустому
  полю. Меняется он при ЛЮБОМ изменении набора или смысла полей.
*/

/** Номер формы данных. Поднимать при любом изменении набора или смысла полей. */
export const ВЕРСИЯ_КОНТРАКТА = 1;

/**
 * Проект в виде, пригодном для передачи: без функций и ссылок по кругу.
 *
 * Намеренно НЕ отдаётся целиком профиль клиента. Наружу идёт только то, что
 * нужно для ответа на вопрос «в каком состоянии проект»: заметки о клиенте,
 * его тексты и внутренние пояснения остаются в файле профиля.
 */
export const проектВКонтракт = п => ({
  id: п.id,
  название: п.профиль.name,
  сайт: п.профиль.site,
  хостинг: п.профиль.hosting,
  cms: п.профиль.cms,
  профильВерен: п.проверка.ок,
  ошибкиПрофиля: п.проверка.ошибки,
  услуги: п.услуги.map(у => ({
    ключ: у.ключ,
    имя: у.имя,
    состояние: у.состояние,
    делали: у.делали,
    нехваткаДоступов: у.нехватка,
  })),
  стадии: п.стадии.map(с => ({ номер: с.стадия.номер, имя: с.стадия.имя, код: с.код, преграды: с.преграды })),
  доступы: п.доступы,
  нехватка: п.нехватка.map(д => ({ имя: д.имя, выдаёт: д.выдаёт, блокируетСтадии: д.блокируетСтадии })),
  отчёт: {
    наполнятся: п.отчёт.наполнятся,
    всего: п.отчёт.всего,
    можноОтправлять: п.отчёт.можноОтправлять,
    почемуНельзя: п.отчёт.почемуНельзя,
  },
});

/**
 * Полный ответ: номер формы, отметка времени и проекты.
 *
 * Время передаётся ВНУТРЬ, а не берётся здесь. Иначе модуль стало бы
 * невозможно проверить: каждый прогон давал бы другой ответ.
 */
export const ответОПроектах = (проекты, когда) => ({
  версияКонтракта: ВЕРСИЯ_КОНТРАКТА,
  собрано: когда,
  проекты: проекты.map(проектВКонтракт),
});
