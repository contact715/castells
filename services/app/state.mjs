/*
  Досыпать проектам данные счётчика.

  ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ ВНУТРИ собратьПроекты, по двум причинам. Первая:
  состояние проектов обязано считаться без базы — это правило, а не
  оптимизация. Вторая: за посещениями надо идти в базу, и делать это при
  каждом сборе состояния (включая командную строку без базы) значило бы
  платить сетью за то, что нужно одной странице.

  Без базы возвращает те же проекты с `посещения: null`. Ноль и «счётчика
  нет» — разные вещи, и рисующий слой должен их различать: первое факт,
  второе наша недоделка.
*/
export async function сПосещениями(проекты, дней = 30) {
  const { итогЗаПериод } = await import('../store/visits.mjs');
  const { БАЗА_ЗАДАНА } = await import('../store/db.mjs');
  if (!БАЗА_ЗАДАНА) return проекты.map(п => ({ ...п, посещения: null }));

  const сДанными = [];
  for (const п of проекты) {
    try {
      сДанными.push({ ...п, посещения: await итогЗаПериод(п.id, дней) });
    } catch {
      /* Молчание тут уместно: страница важнее счётчика, а факт недоступности
         базы уже виден в /health отдельной строкой. */
      сДанными.push({ ...п, посещения: null });
    }
  }
  return сДанными;
}

/*
  Досыпать проектам последний снимок карточки Yelp и сдвиг с прошлого раза.

  Отдельно от посещений, а не одной функцией «дай всё внешнее»: у этих данных
  разная цена. Посещения считает наш счётчик и они всегда под рукой, снимок
  Yelp приходит от инструмента сбора и может отсутствовать месяцами. Свалить их
  в один вызов значило бы ждать оба ради одного.

  Проект без подключённой услуги Yelp пропускается: ходить в базу за данными,
  которые всё равно негде показать, — лишняя работа на каждой отрисовке.
*/
export async function сДаннымиYelp(проекты) {
  const { БАЗА_ЗАДАНА } = await import('../store/db.mjs');
  if (!БАЗА_ЗАДАНА) return проекты.map(п => ({ ...п, yelp: null }));

  const { последнийСнимокYelp, сдвигYelp } = await import('../store/yelp.mjs');
  const сДанными = [];
  for (const п of проекты) {
    const ведёмYelp = п.услуги.some(у => у.ключ === 'yelpAds');
    if (!ведёмYelp) { сДанными.push({ ...п, yelp: null }); continue; }
    try {
      const снимок = await последнийСнимокYelp(п.id);
      сДанными.push({ ...п, yelp: снимок ? { ...снимок, сдвиг: await сдвигYelp(п.id) } : null });
    } catch {
      сДанными.push({ ...п, yelp: null });
    }
  }
  return сДанными;
}
