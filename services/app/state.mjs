/*
  Случай работы: «собрать состояние всех проектов».

  Здесь встречаются две стороны и больше нигде: ХРАНИЛИЩЕ отдаёт сырые
  профили, ЯДРО считает по ним стадии, доступы, отчёт и услуги. Ни одна из
  сторон про другую не знает — ядро не умеет читать файлы, хранилище не знает
  правил.

  Отсюда состояние берут ВСЕ потребители: страница пульта, JSON для агентов,
  командная строка. Раньше каждый собирал сам, и любое расхождение в порядке
  вызовов давало бы разные ответы на один вопрос.
*/

import { прочитатьВсеПрофили } from '../store/clients.mjs';
import { проверитьПрофиль, разобратьПрофиль } from '../core/profile.mjs';
import { СТАДИИ, состояниеСтадии } from '../core/stages.mjs';
import { счётДоступов, нехваткаДоступов } from '../core/access.mjs';
import { готовностьОтчёта } from '../core/report.mjs';
import { услугиПроекта } from '../core/catalog.mjs';

/** Состояние одного проекта по его сырому профилю. */
export function состояниеПроекта(id, сырой) {
  const проверка = проверитьПрофиль(сырой);
  const профиль = разобратьПрофиль(сырой);
  return {
    id,
    профиль,
    проверка,
    стадии: СТАДИИ.map(с => ({ стадия: с, ...состояниеСтадии(с, профиль) })),
    доступы: счётДоступов(профиль),
    нехватка: нехваткаДоступов(профиль),
    отчёт: готовностьОтчёта(профиль),
    услуги: услугиПроекта(профиль),
  };
}

/** Состояние всех заведённых проектов. */
export async function собратьПроекты() {
  const профили = await прочитатьВсеПрофили();
  return профили.map(({ id, сырой }) => состояниеПроекта(id, сырой));
}

