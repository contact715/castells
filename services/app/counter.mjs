/*
  Случай работы: «принять посещение с сайта клиента».

  Соединяет три стороны: ПРАВИЛА (core/visits.mjs — чей домен, что такое
  посетитель), ХРАНИЛИЩЕ (store/visits.mjs — куда писать) и СПИСОК КЛИЕНТОВ
  (store/clients.mjs — какие домены наши).

  ПОЧЕМУ ДОМЕНЫ КЕШИРУЮТСЯ. Событие приходит на каждый просмотр страницы, а
  список сайтов меняется раз в месяц при заведении клиента. Читать четыре
  файла профилей на каждый просмотр — заведомо лишняя работа, которая при
  первом же всплеске посещений станет заметной. Кеш живёт пять минут: новый
  клиент начнёт считаться максимум через пять минут после выкладки, и это
  никому не мешает.
*/

import { прочитатьВсеПрофили } from '../store/clients.mjs';
import { записатьПосещение, сольСуток } from '../store/visits.mjs';
import { домен, отпечаток, устройство, путьСтраницы, источник, почемуНеПринять } from '../core/visits.mjs';

const ЖИЗНЬ_КЕША = 5 * 60 * 1000;
let кеш = { когда: 0, домены: new Map() };

/** Карта «домен → id проекта». */
export async function доменыПроектов(сейчас = Date.now()) {
  if (сейчас - кеш.когда < ЖИЗНЬ_КЕША && кеш.домены.size) return кеш.домены;
  const домены = new Map();
  for (const { id, сырой } of await прочитатьВсеПрофили()) {
    const д = домен(сырой?.site);
    if (д) домены.set(д, id);
  }
  кеш = { когда: сейчас, домены };
  return домены;
}

/** Сбросить кеш. Нужен самопроверкам, чтобы не ждать пять минут. */
export const забытьДомены = () => { кеш = { когда: 0, домены: new Map() }; };

/**
 * Принять событие от скрипта на сайте клиента.
 *
 * ЧУЖОЕ НЕ ПРИНИМАЕМ. Маршрут приёма обязан быть открытым — иначе сайт
 * клиента не сможет ничего прислать, — поэтому единственная защита от мусора
 * здесь: событие засчитывается, только если его источник совпадает с сайтом
 * одного из наших проектов. Чужой домен получает вежливый отказ и НЕ создаёт
 * строки в базе, иначе счётчик стал бы свалкой, которую любой может наполнить.
 */
export async function принятьПосещение({ origin, referer, адресСтраницы, ip, браузер }) {
  const домены = await доменыПроектов();
  /* Origin надёжнее: его ставит браузер и подделать из страницы нельзя.
     Referer — запасной, он бывает урезан политикой сайта. */
  const свой = домен(origin) || домен(referer) || домен(адресСтраницы);
  const проект = домены.get(свой) || null;
  const путь = путьСтраницы(адресСтраницы);

  const отказ = почемуНеПринять({ проект, путь });
  if (отказ) return { принято: false, причина: отказ };

  const соль = await сольСуток();
  if (!соль) return { принято: false, причина: 'база недоступна' };

  const записано = await записатьПосещение({
    проект,
    путь,
    источник: источник(referer, свой),
    устройство: устройство(браузер),
    посетитель: отпечаток({ соль, адрес: ip, браузер, проект }),
  });
  return записано ? { принято: true, проект } : { принято: false, причина: 'запись не удалась' };
}

/*
  Чей это снимок Yelp — по адресу карточки.

  Адрес карточки лежит в профиле клиента (поле `yelp`), поэтому закладка сбора
  не обязана знать, на чьей странице её нажали: она шлёт адрес, а проект
  определяется здесь. Одна закладка работает на всех клиентов, и при заведении
  нового ничего переписывать не надо.

  Сравнение по «слагу» карточки (последний кусок адреса), а не по строке
  целиком: Yelp приклеивает к ссылке хвосты вроде `?osq=` и `&hrid=`, и точное
  сравнение ломалось бы от любого перехода по внутренней ссылке.
*/
const слагYelp = адрес => {
  const м = String(адрес || '').match(/yelp\.[a-z.]+\/biz\/([a-z0-9-]+)/i);
  return м ? м[1].toLowerCase() : '';
};

export async function проектПоКарточкеYelp(адресYelp) {
  const слаг = слагYelp(адресYelp);
  if (!слаг) return null;
  const { прочитатьВсеПрофили } = await import('../store/clients.mjs');
  for (const { id, сырой } of await прочитатьВсеПрофили()) {
    if (слагYelp(сырой?.yelp) === слаг) return id;
  }
  return null;
}

export { слагYelp };
