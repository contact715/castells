/*
  Хранилище снимков публичной карточки Yelp.

  ПОЧЕМУ СНИМКИ, А НЕ «ТЕКУЩЕЕ СОСТОЯНИЕ». Карточка меняется сама: приходят
  отзывы, растёт или падает рейтинг, добавляются фото. Хранить одну строку «как
  сейчас» значило бы затирать вчерашнее и не мочь ответить на главный вопрос
  отчёта — что изменилось за месяц.

  ОТКУДА БЕРУТСЯ ДАННЫЕ И ЧЕГО ЗДЕСЬ НЕТ. Это ПУБЛИЧНАЯ карточка: рейтинг,
  отзывы, фото, отметки Yelp, скорость отклика. Расхода и показов платного
  размещения здесь НЕТ и быть не может — они живут в кабинете рекламы, доступ
  к которому у нас не подтверждён. Смешивать их в одну таблицу нельзя: отчёт
  клиенту тогда покажет «данные по рекламе» там, где на самом деле лежит
  публичная витрина.
*/

import { база } from './db.mjs';

/** Записать снимок. Возвращает true, если запись состоялась. */
export async function записатьСнимокYelp(снимок) {
  const бд = база();
  if (!бд) return false;
  try {
    await бд`INSERT INTO yelp_снимки ${бд({
      проект: снимок.проект,
      адрес_yelp: снимок.адресYelp,
      рейтинг: снимок.рейтинг ?? null,
      отзывов: снимок.отзывов ?? null,
      скрытых: снимок.скрытых ?? null,
      фото: снимок.фото ?? null,
      заявлен: снимок.заявлен ?? null,
      лицензия: снимок.лицензия ?? null,
      гарантия: снимок.гарантия ?? null,
      отклик_время: снимок.откликВремя ?? null,
      отклик_ставка: снимок.откликСтавка ?? null,
      категории: снимок.категории ?? null,
      адрес: снимок.адрес ?? null,
      телефон: снимок.телефон ?? null,
      источник: снимок.источник || 'страница',
    })}`;
    return true;
  } catch (e) {
    console.warn('снимок Yelp не записан:', e.message);
    return false;
  }
}

/** Последний снимок проекта. null, если снимков нет или базы нет. */
export async function последнийСнимокYelp(проект) {
  const бд = база();
  if (!бд) return null;
  try {
    const [строка] = await бд`
      SELECT * FROM yelp_снимки WHERE проект = ${проект}
      ORDER BY когда DESC LIMIT 1
    `;
    return строка || null;
  } catch {
    return null;
  }
}

/**
 * Что изменилось между последним снимком и предыдущим.
 *
 * Возвращает null, когда сравнивать не с чем: один снимок — это ещё не
 * динамика, и рисовать «+0» рядом с числом значило бы показать движение там,
 * где его просто не измеряли.
 */
export async function сдвигYelp(проект) {
  const бд = база();
  if (!бд) return null;
  try {
    const строки = await бд`
      SELECT когда, рейтинг, отзывов, фото FROM yelp_снимки
      WHERE проект = ${проект} ORDER BY когда DESC LIMIT 2
    `;
    if (строки.length < 2) return null;
    const [сейчас, было] = строки;
    return {
      прошлыйСнимок: было.когда,
      рейтинг: сейчас.рейтинг != null && было.рейтинг != null
        ? Number(сейчас.рейтинг) - Number(было.рейтинг) : null,
      отзывов: сейчас.отзывов != null && было.отзывов != null
        ? сейчас.отзывов - было.отзывов : null,
      фото: сейчас.фото != null && было.фото != null
        ? сейчас.фото - было.фото : null,
    };
  } catch {
    return null;
  }
}
