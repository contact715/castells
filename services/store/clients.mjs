import { readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const КОРЕНЬ = dirname(dirname(fileURLToPath(import.meta.url)));
export const ПАПКА_КЛИЕНТОВ = join(КОРЕНЬ, 'clients');

/** Слаги всех заведённых клиентов, по алфавиту. */
export async function перечислитьКлиентов() {
  const файлы = await readdir(ПАПКА_КЛИЕНТОВ);
  return файлы
    .filter(ф => ф.endsWith('.mjs') && !ф.startsWith('_'))
    .map(ф => ф.replace(/\.mjs$/, ''))
    .sort();
}

/** Сырой профиль как он записан в файле. Разбирает его слой выше. */
export async function прочитатьПрофиль(id) {
  const модуль = await import(join(ПАПКА_КЛИЕНТОВ, `${id}.mjs`));
  return модуль.default || модуль.профиль;
}

/** Все профили разом: [{ id, сырой }]. */
export async function прочитатьВсеПрофили() {
  const ids = await перечислитьКлиентов();
  const профили = [];
  for (const id of ids) {
    профили.push({ id, сырой: await прочитатьПрофиль(id) });
  }
  return профили;
}
