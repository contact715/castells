/*
  Подключение к базе и схема.

  ПОЧЕМУ БАЗА ВООБЩЕ ПОЯВИЛАСЬ. Профили клиентов остаются файлами в git — это
  решения о клиенте, и им место в истории репозитория (STACK.md §5). База
  нужна для другого: для того, что НАКАПЛИВАЕТСЯ. Журнал прогонов, показатели
  поиска по датам, данные счётчика, история отправленных отчётов. Это
  временны́е ряды: их пишут регулярно, у них спрашивают «что изменилось за
  месяц», и два процесса пишут в них одновременно. Файл на этом разъезжается.

  ПУЛЬТ ОБЯЗАН РАБОТАТЬ БЕЗ БАЗЫ. Состояние проектов считается из файлов, и
  база к этому непричастна. Если DATABASE_URL не задан или база лежит —
  страница собирается как обычно, а запись в журнал молча пропускается. Иначе
  падение базы превращало бы пульт в белый экран, хотя всё, что он
  показывает, лежит рядом на диске.

  Обратное тоже верно: НЕ делаем вид, что запись прошла. Функция записи
  возвращает, состоялась ли она, а не глотает ошибку под видом успеха.

  ЕДИНСТВЕННАЯ ЗАВИСИМОСТЬ ПРОЕКТА. Драйвер выбран замером, а не по привычке:
  postgres.js (3.4.9) не тянет за собой НИ ОДНОГО пакета, 384 КБ на диске;
  у pg (8.23.0) шесть прямых зависимостей. Проект жил с нулём зависимостей, и
  разменивать это на удобство не стоило.
*/

import postgres from 'postgres';

/** Адрес базы. Пусто — значит базы нет, и это законное состояние. */
const АДРЕС = process.env.DATABASE_URL || '';

/** Есть ли куда писать. Наружу отдаём факт, а не строку с паролем. */
export const БАЗА_ЗАДАНА = Boolean(АДРЕС);

let подключение = null;

/**
 * Подключение по требованию.
 *
 * Ленивое намеренно: модуль импортируют и командная строка, и сервер, и
 * самопроверки. Открывать соединение при импорте значило бы, что любой из них
 * лезет в сеть просто потому, что файл прочитали.
 */
export function база() {
  if (!АДРЕС) return null;
  if (!подключение) {
    подключение = postgres(АДРЕС, {
      max: 4,                 // пульт читает редко; пул на четыре с запасом
      idle_timeout: 20,
      connect_timeout: 10,
      onnotice: () => {},     // «таблица уже существует» — не новость
    });
  }
  return подключение;
}

/** Закрыть соединение. Нужно самопроверкам и командной строке, чтобы не висеть. */
export async function закрыть() {
  if (подключение) {
    await подключение.end({ timeout: 5 });
    подключение = null;
  }
}

/*
  СХЕМА ОДНИМ СПИСКОМ, применяется по порядку и повторно безопасна.

  Отдельного инструмента миграций здесь нет намеренно: он тянет зависимость и
  свой формат ради одной таблицы. Когда шагов станет больше десятка или
  понадобится откат, это перестанет окупаться — тогда и берём инструмент.
  Граница названа заранее, чтобы решение принималось по признаку, а не по
  усталости.
*/
const ШАГИ = [
  {
    имя: '001-журнал-прогонов',
    sql: `
      CREATE TABLE IF NOT EXISTS прогоны (
        id          bigserial PRIMARY KEY,
        когда       timestamptz NOT NULL DEFAULT now(),
        проект      text        NOT NULL,
        стадия      smallint    NOT NULL,
        код         text        NOT NULL,
        преграды    jsonb       NOT NULL DEFAULT '[]'::jsonb,
        длительность_мс integer
      );
      -- Запрашивают всегда «что было у этого проекта в последнее время»,
      -- поэтому индекс по паре, а не по одному полю.
      CREATE INDEX IF NOT EXISTS прогоны_проект_когда ON прогоны (проект, когда DESC);
    `,
  },
  {
    имя: '002-посещения',
    sql: `
      -- Суточная соль для отпечатка посетителя. Лежит в базе, а не в
      -- переменной окружения, по двум причинам: она обязана быть ОДИНАКОВОЙ
      -- у всех реплик сервиса и обязана МЕНЯТЬСЯ каждые сутки. Переменная
      -- окружения даёт первое и не даёт второго.
      CREATE TABLE IF NOT EXISTS соли (
        дата date PRIMARY KEY,
        соль text NOT NULL
      );

      CREATE TABLE IF NOT EXISTS посещения (
        id         bigserial PRIMARY KEY,
        когда      timestamptz NOT NULL DEFAULT now(),
        проект     text        NOT NULL,
        путь       text        NOT NULL,
        источник   text,
        устройство text        NOT NULL,
        -- Не человек, а суточный отпечаток: ни адреса, ни cookie мы не
        -- храним, и связать его со вчерашним нельзя даже нам.
        посетитель text        NOT NULL
      );
      CREATE INDEX IF NOT EXISTS посещения_проект_когда ON посещения (проект, когда DESC);
      -- Считать «сколько разных людей за день» без этого индекса пришлось бы
      -- перебором всей таблицы.
      CREATE INDEX IF NOT EXISTS посещения_проект_посетитель
        ON посещения (проект, посетитель, когда DESC);
    `,
  },
  {
    имя: '003-снимки-yelp',
    sql: `
      -- СНИМОК, А НЕ ТЕКУЩЕЕ СОСТОЯНИЕ. Публичная карточка Yelp меняется
      -- сама: приходят отзывы, меняется рейтинг, обновляются часы. Хранить
      -- «как есть сейчас» значило бы каждый раз терять предыдущее и не мочь
      -- ответить на вопрос «а что изменилось за месяц» — ровно тот вопрос,
      -- ради которого клиент читает отчёт.
      CREATE TABLE IF NOT EXISTS yelp_снимки (
        id         bigserial PRIMARY KEY,
        когда      timestamptz NOT NULL DEFAULT now(),
        проект     text        NOT NULL,
        адрес_yelp text        NOT NULL,
        рейтинг    numeric(2,1),
        отзывов    integer,
        скрытых    integer,
        фото       integer,
        заявлен    boolean,
        лицензия   boolean,
        гарантия   boolean,
        отклик_время text,
        отклик_ставка text,
        категории  text,
        адрес      text,
        телефон    text,
        -- Откуда взят снимок: сегодня «страница», завтра «api». Без этого
        -- поля через месяц не отличить выверенные данные от собранных на
        -- глаз, а доверие к цифре зависит от способа её получения.
        источник   text        NOT NULL DEFAULT 'страница'
      );
      CREATE INDEX IF NOT EXISTS yelp_снимки_проект_когда
        ON yelp_снимки (проект, когда DESC);
    `,
  },
];

/**
 * Применяет схему. Возвращает список выполненных шагов.
 *
 * Отметки о применённых шагах хранятся в самой базе: без этого повторный
 * запуск считался бы новым, и однажды кто-то добавил бы сюда шаг, который
 * повторно выполнять нельзя.
 */
export async function применитьСхему() {
  const бд = база();
  if (!бд) return { применено: [], причина: 'DATABASE_URL не задан' };

  await бд`
    CREATE TABLE IF NOT EXISTS схема_шаги (
      имя   text PRIMARY KEY,
      когда timestamptz NOT NULL DEFAULT now()
    )
  `;
  const было = new Set((await бд`SELECT имя FROM схема_шаги`).map(с => с.имя));

  const применено = [];
  for (const шаг of ШАГИ) {
    if (было.has(шаг.имя)) continue;
    await бд.unsafe(шаг.sql);
    await бд`INSERT INTO схема_шаги ${бд({ имя: шаг.имя })}`;
    применено.push(шаг.имя);
  }
  return { применено, всегоШагов: ШАГИ.length };
}

/**
 * Записать прогон стадии.
 *
 * Возвращает true, если запись состоялась. Ошибка базы не роняет вызывающего:
 * прогон стадии — работа, а журнал — наблюдение за ней, и наблюдение не
 * должно мешать работе. Но и тишины нет: вызывающий видит false и может
 * сказать об этом вслух.
 */
export async function записатьПрогон({ проект, стадия, код, преграды = [], длительностьМс = null }) {
  const бд = база();
  if (!бд) return false;
  try {
    await бд`
      INSERT INTO прогоны ${бд({
        проект,
        стадия,
        код,
        преграды: JSON.stringify(преграды),
        длительность_мс: длительностьМс,
      })}
    `;
    return true;
  } catch (e) {
    console.warn('журнал прогонов недоступен:', e.message);
    return false;
  }
}

/** Последние прогоны проекта — для отчёта «что делали и когда». */
export async function прогоныПроекта(проект, сколько = 50) {
  const бд = база();
  if (!бд) return [];
  return бд`
    SELECT когда, стадия, код, преграды, длительность_мс
    FROM прогоны WHERE проект = ${проект}
    ORDER BY когда DESC LIMIT ${сколько}
  `;
}
