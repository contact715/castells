/*
  Хранилище посещений: запись события и сводки для отчёта.

  Здесь только работа с базой. Что считать посетителем, как обезличить адрес и
  какой домен чей — в core/visits.mjs, потому что это правила, а не хранение.
*/

import { randomBytes } from 'node:crypto';
import { база } from './db.mjs';

/**
 * Соль на сегодняшние сутки: берём из базы, а если её ещё нет — создаём.
 *
 * Гонка здесь реальна: два запроса в одну секунду первого посетителя дня
 * попытаются вставить соль одновременно. Поэтому вставка идёт с ON CONFLICT
 * DO NOTHING, а значение читается ПОСЛЕ неё — тогда оба запроса получат одну
 * и ту же соль, чья бы вставка ни выиграла. Проверка «есть ли уже» с
 * последующей вставкой дала бы двух посетителей вместо одного.
 */
export async function сольСуток(бд = база()) {
  if (!бд) return null;
  const новая = randomBytes(24).toString('hex');
  await бд`
    INSERT INTO соли (дата, соль) VALUES (CURRENT_DATE, ${новая})
    ON CONFLICT (дата) DO NOTHING
  `;
  const [строка] = await бд`SELECT соль FROM соли WHERE дата = CURRENT_DATE`;
  return строка?.соль || null;
}

/** Записать посещение. Возвращает true, если запись состоялась. */
export async function записатьПосещение({ проект, путь, источник, устройство, посетитель }) {
  const бд = база();
  if (!бд) return false;
  try {
    await бд`
      INSERT INTO посещения ${бд({ проект, путь, источник, устройство, посетитель })}
    `;
    return true;
  } catch (e) {
    console.warn('посещение не записано:', e.message);
    return false;
  }
}

/**
 * Сводка по проекту за последние N суток — то, ради чего счётчик и ставится:
 * две строки в ежемесячный отчёт клиенту.
 *
 * Дни без посещений в ответе ОТСУТСТВУЮТ, и это осознанно: заполнять их
 * нулями должен тот, кто рисует, — он знает, за какой период показывает.
 * Хранилище не выдумывает строк, которых нет.
 */
export async function сводкаПоДням(проект, дней = 30) {
  const бд = база();
  if (!бд) return [];
  return бд`
    SELECT date_trunc('day', когда)::date AS день,
           count(*)::int                  AS просмотры,
           count(DISTINCT посетитель)::int AS посетители
    FROM посещения
    WHERE проект = ${проект} AND когда > now() - (${дней} || ' days')::interval
    GROUP BY 1 ORDER BY 1
  `;
}

/** Итог за период одной строкой: сколько просмотров и сколько людей. */
export async function итогЗаПериод(проект, дней = 30) {
  const бд = база();
  if (!бд) return { просмотры: 0, посетители: 0, естьДанные: false };
  const [строка] = await бд`
    SELECT count(*)::int AS просмотры, count(DISTINCT посетитель)::int AS посетители
    FROM посещения
    WHERE проект = ${проект} AND когда > now() - (${дней} || ' days')::interval
  `;
  return {
    просмотры: строка?.просмотры ?? 0,
    посетители: строка?.посетители ?? 0,
    /* Отличаем «ноль посещений» от «счётчик не стоит»: в отчёте это разные
       вещи, и путать их нельзя — первое факт, второе наша недоделка. */
    естьДанные: (строка?.просмотры ?? 0) > 0,
  };
}

/** Самые посещаемые страницы — для разбора, а не для отчёта клиенту. */
export async function топСтраниц(проект, дней = 30, сколько = 10) {
  const бд = база();
  if (!бд) return [];
  return бд`
    SELECT путь, count(*)::int AS просмотры
    FROM посещения
    WHERE проект = ${проект} AND когда > now() - (${дней} || ' days')::interval
    GROUP BY путь ORDER BY просмотры DESC LIMIT ${сколько}
  `;
}
