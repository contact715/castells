#!/usr/bin/env node
/**
 * Замер видимости в ответах ИИ. Заведён 1 сентября 2026 по спеке
 * services/docs/SPEC_AI_VISIBILITY.md.
 *
 * ЧТО ЭТО МЕРЯЕТ. Не позицию в поиске, а другое: назовёт ли движок бизнес,
 * когда человек спрашивает его совета. В выдаче быть шестым плохо, но видно;
 * в ответе движка шестого места нет — называют двоих-троих, остальных не
 * существует.
 *
 * ГЛАВНОЕ ПРАВИЛО ЗАМЕРА: вопрос задаётся ЧИСТО. Ни в запросе, ни в системной
 * подсказке нет ни имени клиента, ни намёка на него. Иначе меряется не то,
 * что движок знает, а то, что мы ему подсказали.
 *
 * По этой же причине замер нельзя делать «из головы» той модели, которая
 * ведёт работу: у неё в разговоре уже лежит всё про клиента, и её ответ
 * заражён. Нужен отдельный вызов по API, с чистого листа.
 *
 * ДОЛЯ, А НЕ ЧИСЛО УПОМИНАНИЙ. Считается доля вопросов, где бизнес назван,
 * против ПОИМЕНОВАННЫХ конкурентов. Абсолютное число упоминаний не
 * показывается вовсе: оно растёт просто от того, что задали больше вопросов,
 * и график получается красивый там, где ничего не изменилось.
 *
 * ОТПЕЧАТОК НАБОРА. У каждого прогона сохраняется отпечаток списка вопросов.
 * Поменялся список — поменялся отпечаток, и сравнивать прогоны между собой
 * уже нельзя. Без этого скачок от смены вопросов неотличим от движения рынка.
 *
 * Запуск:
 *   node tools/ai-visibility.mjs --client castells
 *   node tools/ai-visibility.mjs --client castells --limit 5   (короткий прогон)
 *   node tools/ai-visibility.mjs --self-test
 */

import { createHash } from 'node:crypto';
import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/* ─────────────────────────── движки ─────────────────────────── */

/**
 * Каждый движок обязан назвать, ЧЕМ получен ответ. Поле `источник` уходит в
 * запись рядом с числом: через полгода никто иначе не скажет, сравнимы ли
 * замеры января и июня.
 */
export const ДВИЖКИ = {
  google: {
    имя: 'Google Gemini',
    источник: 'google-generativelanguage-api',
    ключИз: ['GOOGLE_GENAI_API_KEY', 'GEMINI_API_KEY'],
    модель: 'gemini-2.5-flash',
    async спросить(вопрос, ключ, модель) {
      const r = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${модель}:generateContent?key=${ключ}`,
        {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ contents: [{ parts: [{ text: вопрос }] }] }),
        }
      );
      if (!r.ok) throw new Error(`${r.status} ${(await r.text()).slice(0, 120)}`);
      const d = await r.json();
      return d.candidates?.[0]?.content?.parts?.map((p) => p.text).join('') ?? '';
    },
  },
  openai: {
    имя: 'OpenAI',
    источник: 'openai-chat-completions',
    ключИз: ['OPENAI_API_KEY'],
    модель: 'gpt-4o-mini',
    async спросить(вопрос, ключ, модель) {
      const r = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: { Authorization: `Bearer ${ключ}`, 'Content-Type': 'application/json' },
        body: JSON.stringify({ model: модель, messages: [{ role: 'user', content: вопрос }] }),
      });
      if (!r.ok) throw new Error(`${r.status} ${(await r.text()).slice(0, 120)}`);
      const d = await r.json();
      return d.choices?.[0]?.message?.content ?? '';
    },
  },
};

/* ─────────────────────── разбор ответа ─────────────────────── */

/**
 * Кого движок назвал. Ищем имена компаний: слова с заглавной, идущие подряд,
 * плюс явные маркеры списка.
 *
 * Это НЕ идеальный разбор имён, и он таким не притворяется: он находит
 * кандидатов, а решение «это компания или нет» принимает список известных нам
 * конкурентов плюс глаз человека при проверке. Автоматический разбор, выданный
 * за истину, — как раз то, из-за чего такие отчёты и врут.
 */
export function найтиНазванных(текст) {
  const кандидаты = new Map();
  const строки = String(текст).split('\n');
  for (const строка of строки) {
    // из нумерованных и маркированных списков имя берём до тире или двоеточия
    const сп = строка.match(/^\s*(?:\d+[.)]|[-*•])\s*\*{0,2}([^*\n:—–-]{3,60})/);
    if (сп) {
      const имя = сп[1].trim().replace(/\s+/g, ' ');
      if (/[A-Za-z]/.test(имя) && имя.split(' ').length <= 7) {
        кандидаты.set(имя, (кандидаты.get(имя) ?? кандидаты.size) );
      }
    }
  }
  return [...кандидаты.keys()];
}

/** Назван ли бизнес: по имени и по домену, оба варианта. */
export function найденБизнес(текст, { имена = [], домены = [] }) {
  const t = String(текст).toLowerCase();
  for (const и of имена) if (и && t.includes(и.toLowerCase())) return { найден: true, как: и };
  for (const д of домены) if (д && t.includes(д.toLowerCase())) return { найден: true, как: д };
  return { найден: false, как: null };
}

/** Позиция бизнеса в списке названных, начиная с 1. Ноль — не назван. */
export function позицияВСписке(названные, { имена = [], домены = [] }) {
  const ключи = [...имена, ...домены].filter(Boolean).map((x) => x.toLowerCase());
  for (let i = 0; i < названные.length; i++) {
    const n = названные[i].toLowerCase();
    if (ключи.some((k) => n.includes(k) || k.includes(n))) return i + 1;
  }
  return 0;
}

/** Отпечаток набора вопросов: сменился набор — сравнивать прогоны нельзя. */
export function отпечатокНабора(вопросы) {
  return createHash('sha256').update(вопросы.join('\n')).digest('hex').slice(0, 12);
}

/* ─────────────────────── свёртка прогона ─────────────────────── */

export function свести(ответы) {
  const всего = ответы.length;
  /*
    ПРОГОН С ОШИБКАМИ НЕ ПРЕВРАЩАЕТСЯ В НОЛЬ ПРОЦЕНТОВ.

    Первый настоящий прогон 2 сентября 2026 дал 16 ошибок из 16: у ключа не
    оказалось доступа к текстовым моделям. Свод при этом честно посчитал «0%
    доля рекомендаций» — и это выглядело ровно как «нас не называют нигде».

    Два состояния мира, дающие одно число: нас не знают, и мы не спросили.
    Их нельзя показывать одинаково, потому что первое требует работы, а второе
    требует ключа.

    Порог в половину: если больше половины вопросов не получили ответа, свода
    нет вовсе, есть отметка о несостоявшемся замере.
  */
  const ошибок = ответы.filter((о) => о.ошибка).length;
  if (всего === 0 || ошибок > всего / 2) {
    return {
      состоялся: false,
      вопросов: всего,
      ошибок,
      причина: ответы.find((о) => о.ошибка)?.ошибка?.slice(0, 160) ?? 'вопросов не задано',
    };
  }
  const сНами = ответы.filter((о) => о.найден).length;
  const позиции = ответы.filter((о) => о.позиция > 0).map((о) => о.позиция);
  const конкуренты = new Map();
  for (const о of ответы) {
    for (const имя of о.названные) {
      if (о.наше?.includes(имя)) continue;
      конкуренты.set(имя, (конкуренты.get(имя) ?? 0) + 1);
    }
  }
  const топ = [...конкуренты.entries()].sort((a, b) => b[1] - a[1]);
  const всехУпоминаний = [...конкуренты.values()].reduce((s, n) => s + n, 0) + сНами;
  return {
    состоялся: true,
    ошибок,
    вопросов: всего,
    найдены_в: сНами,
    доля_вопросов_с_нами: всего ? +(сНами / всего * 100).toFixed(1) : 0,
    // доля против ПОИМЕНОВАННЫХ конкурентов, а не абсолютные упоминания
    доля_рекомендаций: всехУпоминаний ? +(сНами / всехУпоминаний * 100).toFixed(1) : 0,
    средняя_позиция: позиции.length ? +(позиции.reduce((s, p) => s + p, 0) / позиции.length).toFixed(1) : null,
    конкуренты: топ.slice(0, 15).map(([имя, n]) => ({ имя, упоминаний: n })),
  };
}

/* ─────────────────────────── прогон ─────────────────────────── */

export async function прогнать({ клиент, движок, вопросы, ключ, модель, пауза = 400, наПрогресс }) {
  const д = ДВИЖКИ[движок];
  if (!д) throw new Error(`движок «${движок}» неизвестен`);
  const ответы = [];
  for (let i = 0; i < вопросы.length; i++) {
    const вопрос = вопросы[i];
    let текст = '', ошибка = null;
    try {
      текст = await д.спросить(вопрос, ключ, модель || д.модель);
    } catch (e) {
      ошибка = String(e.message).slice(0, 140);
    }
    const названные = найтиНазванных(текст);
    const { найден, как } = найденБизнес(текст, клиент);
    ответы.push({
      вопрос,
      ответ: текст,
      ошибка,
      названные,
      найден,
      как,
      наше: [...(клиент.имена ?? []), ...(клиент.домены ?? [])],
      позиция: позицияВСписке(названные, клиент),
    });
    наПрогресс?.(i + 1, вопросы.length, найден);
    if (пауза) await new Promise((r) => setTimeout(r, пауза));
  }
  return {
    клиент: клиент.id,
    движок,
    источник: д.источник,
    модель: модель || д.модель,
    когда: new Date().toISOString(),
    версия_набора: отпечатокНабора(вопросы),
    ответы,
    свод: свести(ответы),
  };
}

/* ─────────────────────── сохранение ─────────────────────── */

/**
 * Пока базы нет, прогон кладётся файлом. Сырые ответы сохраняются ЦЕЛИКОМ:
 * без них нельзя спорить с клиентом фактами, а спор про числа ИИ будет
 * тяжелее, чем про позиции в поиске.
 */
export async function сохранить(прогон) {
  const папка = path.join(КОРЕНЬ, 'data', 'ai-visibility');
  await mkdir(папка, { recursive: true });
  const имя = `${прогон.клиент}-${прогон.движок}-${прогон.когда.slice(0, 10)}-${прогон.версия_набора}.json`;
  const путь = path.join(папка, имя);
  await writeFile(путь, JSON.stringify(прогон, null, 2), 'utf8');
  return путь;
}

/* ─────────────────────── самопроверка ─────────────────────── */

async function самопроверка() {
  const п = [];
  const t = (имя, условие) => п.push([имя, Boolean(условие)]);

  const образец = `Here are the top agencies:
1. Hook Agency - great for contractors
2. Castells Media - publishes prices
3. Blackstorm Design`;
  const названные = найтиНазванных(образец);
  t('разбирает нумерованный список', названные.length === 3);
  t('имя берётся до тире', названные[0] === 'Hook Agency');

  const клиент = { имена: ['Castells Media', 'Castells'], домены: ['castells.media'] };
  t('находит бизнес по имени', найденБизнес(образец, клиент).найден);
  t('позиция считается с единицы', позицияВСписке(названные, клиент) === 2);
  t('не находит того, кого нет', !найденБизнес(образец, { имена: ['Nonexistent Co'] }).найден);

  t('отпечаток устойчив', отпечатокНабора(['a', 'b']) === отпечатокНабора(['a', 'b']));
  t('отпечаток меняется со списком', отпечатокНабора(['a']) !== отпечатокНабора(['a', 'b']));

  const свод = свести([
    { найден: true, позиция: 2, названные: ['Hook Agency', 'Castells Media'], наше: ['Castells Media'] },
    { найден: false, позиция: 0, названные: ['Hook Agency', 'Other Co'], наше: ['Castells Media'] },
  ]);
  t('доля вопросов с нами', свод.доля_вопросов_с_нами === 50);
  t('конкуренты посчитаны', свод.конкуренты.find((к) => к.имя === 'Hook Agency')?.упоминаний === 2);
  t('своё имя не попало в конкурентов', !свод.конкуренты.some((к) => к.имя === 'Castells Media'));
  t('средняя позиция только по найденным', свод.средняя_позиция === 2);
  t('доля рекомендаций не равна доле вопросов', свод.доля_рекомендаций !== свод.доля_вопросов_с_нами);

  const пустой = свести([]);
  t('пустой прогон помечен несостоявшимся, а не нулевым',
    пустой.состоялся === false && пустой.доля_рекомендаций === undefined);

  t('у каждого движка назван источник', Object.values(ДВИЖКИ).every((д) => д.источник));

  // Главное: провалившийся прогон не должен выглядеть как «нас не называют»
  const провал = свести([
    { ошибка: '404 no access', найден: false, позиция: 0, названные: [], наше: [] },
    { ошибка: '404 no access', найден: false, позиция: 0, названные: [], наше: [] },
    { ошибка: null, найден: false, позиция: 0, названные: ['Hook Agency'], наше: [] },
  ]);
  t('прогон с большинством ошибок помечен несостоявшимся', провал.состоялся === false);
  t('у несостоявшегося нет доли рекомендаций', провал.доля_рекомендаций === undefined);
  t('у несостоявшегося названа причина', typeof провал.причина === 'string' && провал.причина.length > 3);

  const частичный = свести([
    { ошибка: '500', найден: false, позиция: 0, названные: [], наше: [] },
    { ошибка: null, найден: true, позиция: 1, названные: ['Castells Media'], наше: ['Castells Media'] },
    { ошибка: null, найден: false, позиция: 0, названные: ['Hook Agency'], наше: ['Castells Media'] },
  ]);
  t('одна ошибка из трёх прогон не отменяет', частичный.состоялся === true);
  t('число ошибок сохранено в своде', частичный.ошибок === 1);

  for (const [имя, ок] of п) console.log(`  ${ок ? 'ok  ' : 'ПЛОХО'} ${имя}`);
  const плохо = п.filter(([, о]) => !о);
  console.log(`\n${п.length - плохо.length}/${п.length} проверок пройдено`);
  return плохо.length ? 1 : 0;
}

/* ─────────────────────────── запуск ─────────────────────────── */

const этоГлавный = process.argv[1] === fileURLToPath(import.meta.url);
if (этоГлавный && process.argv.includes('--self-test')) {
  process.exit(await самопроверка());
}
