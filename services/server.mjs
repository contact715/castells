#!/usr/bin/env node
/*
  Точка входа сервиса. Railway запускает именно этот файл (startCommand
  «node server.mjs»), поэтому он остаётся на месте и с прежним именем.

  Внутри — ничего, кроме подъёма сервера: маршруты, вход по паролю и сборка
  ответа живут в web/http.mjs. Разделение нужно ровно за тем, чтобы имя точки
  входа не диктовало устройство кода: сегодня это Railway, завтра другой
  запускатель, а слои останутся теми же.
*/

import { fileURLToPath } from 'node:url';
import { поднять, подготовитьБазу, ПАРОЛЬ_ЗАДАН } from './web/http.mjs';

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  подготовитьБазу().then(итог => {
    if (итог.применено?.length) console.log(`Схема базы: применено ${итог.применено.join(', ')}`);
    else if (итог.причина) console.log(`База не готовится: ${итог.причина}`);
    else console.log('Схема базы: уже на месте');
  });

  поднять().then(сервер => {
    const { port } = сервер.address();
    console.log(`Пульт слушает порт ${port}`);
    if (!ПАРОЛЬ_ЗАДАН) {
      console.warn('DASHBOARD_TOKEN не задан — пульт ЗАКРЫТ для всех, отдаёт 503. Задайте переменную и перезапустите.');
    }
  });

  // Railway останавливает контейнер сигналом: закрываемся сами, чтобы выкатка
  // не ждала таймаута.
  for (const сигнал of ['SIGTERM', 'SIGINT']) {
    process.on(сигнал, () => { console.log(`Получен ${сигнал}, останавливаюсь`); process.exit(0); });
  }
}
