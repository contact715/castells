const переменные = набор =>
  Object.entries(набор)
    .map(([имя, значение]) => `--${имя}:${значение};`)
    .join('');

/**
 * Готовый блок объявлений тем. Тёмная — основа, светлая — только по явному
 * выбору. Так же, как в их ThemeProvider.
 */
