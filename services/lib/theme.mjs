/** Ширина бокового меню и высота верхней панели. */
export const РАЗМЕРЫ = {
  сайдбар: '248px',
  панель: '56px',
  радиус: '4px',
};

/**
 * Шрифты. Подключаются с Google Fonts, поэтому здесь и имена, и строка
 * подключения — чтобы не разъехались.
 */
export const ШРИФТЫ = {
  подключение:
    'https://fonts.googleapis.com/css2?family=Archivo:wght@500;600;700&family=Source+Sans+3:wght@400;600&family=IBM+Plex+Mono:wght@400;500&display=swap',
  заголовки: 'Archivo, system-ui, sans-serif',
  текст: '"Source Sans 3", system-ui, -apple-system, sans-serif',
  моно: '"IBM Plex Mono", ui-monospace, monospace',
};

/**
 * Цвета. Светлая тема — основная, тёмная перекрывает только значения.
 *
 * Нейтральные оттенки уведены в холодную сторону под акцент, а не взяты
 * серыми из середины палитры: ровный серый выглядит как «не выбирали».
 */
export const СВЕТЛАЯ = {
  ground: '#FBFBFC',
  surface: '#FFFFFF',
  sunk: '#F4F6F7',
  ink: '#141A21',
  neutral: '#5C6672',
  hair: '#E2E6EA',
  accent: '#0E5E63',
  ok: '#2C7A57',
  no: '#B0442E',
  wait: '#9A7223',
  human: '#4A5568',
};

export const ТЁМНАЯ = {
  ground: '#0F1418',
  surface: '#161D23',
  sunk: '#111820',
  ink: '#E8EDF1',
  neutral: '#93A0AC',
  hair: '#242E36',
  accent: '#4FB3B8',
  ok: '#4FA37B',
  no: '#D9705A',
  wait: '#C9A14E',
  human: '#8996A5',
};

const переменные = набор =>
  Object.entries(набор)
    .map(([имя, значение]) => `--${имя}:${значение};`)
    .join('');

/**
 * Готовый блок объявлений тем.
 *
 * Три состояния, а не два: явный выбор ставит на корне data-theme, а
 * настройка «как в системе» не ставит ничего — и тогда светлую от тёмной
 * отличает только prefers-color-scheme. Поэтому тёмная объявлена дважды.
 */
export const темы = () => `
  :root{${переменные(СВЕТЛАЯ)}--сайдбар:${РАЗМЕРЫ.сайдбар};--панель:${РАЗМЕРЫ.панель};--радиус:${РАЗМЕРЫ.радиус};}
  @media (prefers-color-scheme: dark){
    :root:not([data-theme="light"]){${переменные(ТЁМНАЯ)}}
  }
  :root[data-theme="dark"]{${переменные(ТЁМНАЯ)}}
`;
