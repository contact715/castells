/** Ремёсла, под которые у нас есть курс академии и понимание ниши. */
export const РЕМЁСЛА = ['hvac', 'remodeling', 'roofing', 'automotive', 'professional', 'other'];

/*
  Доступы переехали в lib/access.mjs и стали справочником: у каждого написано,
  зачем он и какие стадии без него встают. Здесь оставлен реэкспорт, чтобы не
  ломать тех, кто уже импортировал ДОСТУПЫ отсюда.

  Почему переехали. Четырёх «гугловых» доступов оказалось мало и не про то:
  работа упирается в хостинг и DNS, а без записи в DNS не подтверждается даже
  Search Console. Список из четырёх галочек создавал впечатление, что всё
  просто, и это впечатление было ложным.
*/
export { ДОСТУПЫ, ХОСТИНГИ } from './access.mjs';
import { УСЛУГИ, СОСТОЯНИЯ } from './catalog.mjs';
import { ДОСТУПЫ as СПРАВОЧНИК_ДОСТУПОВ, ХОСТИНГИ as СПРАВОЧНИК_ХОСТИНГОВ } from './access.mjs';

/**
 * Ищет числа без источника в свободном тексте.
 *
 * Намеренно грубо и с перестраховкой: лучше лишний раз спросить у человека,
 * чем пропустить «увеличили заявки на 40%» в текст клиента. Год (2026),
 * телефон и цену с валютой не трогаем — это не заявления о результате.
 */
export function числаБезИсточника(текст) {
  if (typeof текст !== 'string') return [];
  const найдено = [];
  // Числа, похожие на заявление о результате: процент, «в N раз», просто число
  // рядом со словом роста. Валюту и годы пропускаем.
  const подозрительные = текст.match(/\b\d[\d\s.,]*\s*(%|percent|x\b|раз)/gi) || [];
  for (const кусок of подозрительные) найдено.push(кусок.trim());
  return найдено;
}

/** Пустое значение: null, undefined, пустая строка или пустой массив. */
const пусто = значение =>
  значение == null ||
  (typeof значение === 'string' && значение.trim() === '') ||
  (Array.isArray(значение) && значение.length === 0);

/**
 * Проверка профиля. Возвращает { ок, ошибки, предупреждения }.
 *
 * Ошибка — профиль нельзя пускать в работу. Предупреждение — работать можно,
 * но человек должен знать. Разделение важно: если всё считать ошибкой, люди
 * начнут отключать проверку целиком, и она перестанет защищать.
 */
export function проверитьПрофиль(профиль) {
  const ошибки = [];
  const предупреждения = [];

  const требуется = (поле, значение) => {
    if (пусто(значение)) ошибки.push(`не заполнено обязательное поле: ${поле}`);
  };

  требуется('id', профиль?.id);
  требуется('name', профиль?.name);
  требуется('trade', профиль?.trade);
  требуется('services', профиль?.services);
  требуется('cities', профиль?.cities);
  требуется('cms', профиль?.cms);

  if (профиль?.id && профиль.id !== slugify(профиль.id)) {
    ошибки.push(`id должен быть слагом: ожидалось «${slugify(профиль.id)}», указано «${профиль.id}»`);
  }

  if (профиль?.trade && !РЕМЁСЛА.includes(профиль.trade)) {
    ошибки.push(`неизвестное ремесло «${профиль.trade}», ожидалось одно из: ${РЕМЁСЛА.join(', ')}`);
  }

  if (профиль?.cms && !CMS[профиль.cms]) {
    ошибки.push(`неизвестная CMS «${профиль.cms}», ожидалось одно из: ${Object.keys(CMS).join(', ')}`);
  }

  if (профиль?.cms === 'unknown') {
    предупреждения.push('CMS не выяснена — до старта работ выяснить, иначе публикация страниц не спланируется');
  }

  // Услуги и города — из них собирается структура страниц, поэтому проверяем
  // не только наличие, но и то, что слаги не схлопнутся в одинаковые.
  const слагиУслуг = new Map();
  for (const услуга of профиль?.services || []) {
    const имя = typeof услуга === 'string' ? услуга : услуга?.name;
    if (пусто(имя)) { ошибки.push('в списке услуг есть запись без названия'); continue; }
    const слаг = slugify(имя);
    if (слагиУслуг.has(слаг)) {
      ошибки.push(`две услуги дают один адрес «${слаг}»: «${слагиУслуг.get(слаг)}» и «${имя}»`);
    }
    слагиУслуг.set(слаг, имя);
  }

  const слагиГородов = new Map();
  for (const город of профиль?.cities || []) {
    const имя = typeof город === 'string' ? город : город?.name;
    if (пусто(имя)) { ошибки.push('в списке городов есть запись без названия'); continue; }
    const слаг = slugify(имя);
    if (слагиГородов.has(слаг)) {
      ошибки.push(`два города дают один адрес «${слаг}»: «${слагиГородов.get(слаг)}» и «${имя}»`);
    }
    слагиГородов.set(слаг, имя);
  }

  // Факты: у каждого обязан быть источник. Это то самое правило, из-за
  // нарушения которого на нашем собственном сайте трижды находили выдумку.
  for (const факт of профиль?.facts || []) {
    if (пусто(факт?.claim)) { ошибки.push('в списке фактов есть запись без утверждения'); continue; }
    if (пусто(факт?.source)) {
      ошибки.push(`факт без источника: «${факт.claim}» — либо укажите источник, либо уберите факт`);
    }
  }

  // Свободные тексты профиля не должны нести чисел-заявлений: для чисел есть
  // facts, где источник обязателен.
  for (const поле of ['tagline', 'about', 'differentiator']) {
    for (const число of числаБезИсточника(профиль?.[поле])) {
      ошибки.push(`число без источника в поле ${поле}: «${число}» — перенесите в facts с источником`);
    }
  }

  // Хостинг: без него не выкатить правки, даже если они написаны.
  if (профиль?.hosting && !СПРАВОЧНИК_ХОСТИНГОВ[профиль.hosting]) {
    ошибки.push(
      `неизвестный хостинг «${профиль.hosting}», ожидалось одно из: ` +
      `${Object.keys(СПРАВОЧНИК_ХОСТИНГОВ).join(', ')}`,
    );
  }
  if (профиль?.site && !профиль?.hosting) {
    предупреждения.push('сайт есть, а хостинг не указан — непонятно, куда выкатывать правки');
  }

  // Подключённые услуги: проект без единой услуги — это не проект, а запись
  // в списке. Пустое поле не ошибка (клиента могли только завести), но сказать
  // об этом надо.
  const подключено = профиль?.engaged || {};
  const ключиУслуг = Object.keys(подключено);
  if (!ключиУслуг.length) {
    предупреждения.push('ни одна услуга не подключена — непонятно, что мы для клиента делаем');
  }
  for (const [ключ, состояние] of Object.entries(подключено)) {
    if (!УСЛУГИ[ключ]) {
      ошибки.push(`неизвестная услуга «${ключ}» — опечатка или её нет в каталоге`);
      continue;
    }
    if (!СОСТОЯНИЯ.includes(состояние)) {
      ошибки.push(
        `у услуги «${УСЛУГИ[ключ].имя}» непонятное состояние «${состояние}», ` +
        `ожидалось одно из: ${СОСТОЯНИЯ.join(', ')}`,
      );
    }
  }

  // Доступы — не ошибка, но от них зависит, какие стадии вообще выполнимы.
  const доступы = профиль?.access || {};
  for (const [ключ, д] of Object.entries(СПРАВОЧНИК_ДОСТУПОВ)) {
    if (доступы[ключ]) continue;
    const стадии = д.стадии.length ? ` — встают стадии ${д.стадии.join(', ')}` : '';
    предупреждения.push(`нет доступа «${д.имя}»${стадии}`);
  }
  for (const ключ of Object.keys(доступы)) {
    if (!СПРАВОЧНИК_ДОСТУПОВ[ключ]) {
      ошибки.push(`в access указан неизвестный доступ «${ключ}» — опечатка или его нет в справочнике`);
    }
  }

  return { ок: ошибки.length === 0, ошибки, предупреждения };
}

/** Нормализует услуги и города к единому виду { name, slug }. */
export function разобратьПрофиль(профиль) {
  const кЗаписи = значение =>
    typeof значение === 'string'
      ? { name: значение, slug: slugify(значение) }
      : { ...значение, slug: значение.slug || slugify(значение.name) };

  return {
    ...профиль,
    services: (профиль.services || []).map(кЗаписи),
    cities: (профиль.cities || []).map(кЗаписи),
  };
}
