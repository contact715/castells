/*
  Ежемесячный отчёт клиенту.

  Почему он заложен в процесс, а не пишется когда вспомним. Отчёт — это то,
  за что клиент продлевает работу. Если его нет, через три месяца разговор
  всегда один и тот же: «а что вы вообще сделали». Разбор стратегии 28 августа
  говорит об этом прямо: без измерения работа не доказана, и продлевать её
  не за что.

  ГЛАВНОЕ ПРАВИЛО ОТЧЁТА, И ОНО ЖЁСТЧЕ ОСТАЛЬНЫХ. В отчёт не идёт ни одно
  число, которого мы не можем показать в первоисточнике. Не «трафик вырос» —
  а снимок из Search Console. Не «позиции улучшились» — а конкретные запросы
  с датами. Раздел, для которого нет данных, в отчёте помечается как
  «нет данных, потому что <причина>», а не выбрасывается и не заполняется
  ощущениями. Пустой раздел с названной причиной — это давление на того, кто
  может причину устранить. Выброшенный раздел — это тишина.
*/

