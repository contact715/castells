/**
 * Готовность отчёта по конкретному проекту: какие разделы наполнятся, какие
 * встанут и почему.
 *
 * Отдельно считаем, можно ли вообще отправлять отчёт: если ни один
 * обязательный раздел не наполняется, отчёт получится письмом «мы работали»,
 * и отправлять такое хуже, чем не отправлять.
 */
export function готовностьОтчёта(профиль) {
  const есть = профиль?.access || {};

  // Раздел наполняется, только когда сошлось И то, и другое: есть доступ к
  // данным И подключена услуга, которая эти данные производит. Без второго
  // условия отчёт обещал бы раздел «Реклама» клиенту, которому мы рекламу не
  // ведём, — и выглядел бы как недоработка вместо честной картины.
  const отУслуг = new Set(разделыОтУслуг(профиль));
  const разделы = РАЗДЕЛЫ.map(р => {
    const нет = р.нужныДоступы.filter(д => !есть[д]);
    const услугаЕсть = р.нужныДоступы.length === 0 || отУслуг.has(р.id);
    const мешает = нет.map(д => ДОСТУПЫ[д]?.имя || д);
    if (!услугаЕсть) мешает.push('услуга не подключена');
    return {
      ...р,
      наполнится: нет.length === 0 && услугаЕсть,
      мешает,
    };
  });

  const обязательные = разделы.filter(р => р.обязателен);
  const наполнятся = разделы.filter(р => р.наполнится);
  const обязательныеНаполнятся = обязательные.filter(р => р.наполнится);

  // «Что сделали» и «что дальше» мы можем написать всегда — но отчёт, где есть
  // только они, не отвечает на вопрос клиента «что мне это дало».
  const толькоОНас = обязательныеНаполнятся.every(р => р.id === 'work' || р.id === 'next');

  return {
    разделы,
    наполнятся: наполнятся.length,
    всего: разделы.length,
    можноОтправлять: обязательныеНаполнятся.length > 0 && !толькоОНас,
    почемуНельзя: толькоОНас
      ? 'наполняются только разделы о нашей работе; на вопрос «что мне это дало» отчёт не отвечает'
      : обязательныеНаполнятся.length === 0
        ? 'ни один обязательный раздел не наполняется'
        : null,
  };
}

/** Дата следующего отчёта от заданного дня. */
export function следующийОтчёт(от = new Date()) {
  const год = от.getUTCFullYear();
  const месяц = от.getUTCMonth();
  const вЭтомМесяце = new Date(Date.UTC(год, месяц, ДЕНЬ_ОТЧЁТА));
  return от.getUTCDate() < ДЕНЬ_ОТЧЁТА
    ? вЭтомМесяце
    : new Date(Date.UTC(год, месяц + 1, ДЕНЬ_ОТЧЁТА));
}
