#!/usr/bin/env node
/*
  Самопроверки проекта. Запуск: node services/seo/self-test.mjs

  Зачем они здесь с первого дня, а не «когда-нибудь потом». На основном сайте
  самопроверка генератора страниц существовала, но её никто не запускал, и она
  молча краснела. Хуже того: 27 августа выяснилось, что проверка длины описаний
  смотрела лишь на четверть страниц, и зелёный результат ничего не доказывал
  про остальные три четверти.

  Из этого два правила, которые здесь соблюдаются:
    1. проверка запускается одной командой и падает громко;
    2. проверка смотрит на то же, что использует рабочий код, а не на свой
       отдельный список.
*/

import { slugify, проверитьПрофиль, числаБезИсточника } from './lib/profile.mjs';
import { собратьПлан, путиДляЗамера, ПРЕДЕЛ_ЗАГОЛОВКА, ПРЕДЕЛ_ОПИСАНИЯ, ПОРОГ_ТОНКИХ } from './lib/plan.mjs';
import { СТАДИИ, преградыСтадии } from './lib/stages.mjs';
import { ДОСТУПЫ, ХОСТИНГИ, счётДоступов, нехваткаДоступов } from './lib/access.mjs';
import { готовностьОтчёта, следующийОтчёт, РАЗДЕЛЫ, ДЕНЬ_ОТЧЁТА } from './lib/report.mjs';
import castells from './clients/castells.mjs';
import { ИСПОЛНИТЕЛИ } from './run.mjs';
import { собратьПроекты, страница } from './dashboard.mjs';
import образец from './clients/_template.mjs';

let всего = 0;
let упало = 0;

const проверка = (имя, условие, подробность = '') => {
  всего++;
  if (условие) {
    console.log(`  ok  ${имя}`);
  } else {
    упало++;
    console.log(`  ПАДЕНИЕ  ${имя}${подробность ? ` — ${подробность}` : ''}`);
  }
};

console.log('Самопроверки цикла SEO\n');

// --- слаги: урок 25 августа ---
проверка('амперсанд читается как and', slugify('ADU & Additions') === 'adu-and-additions', slugify('ADU & Additions'));
проверка('косая черта не создаёт уровень вложенности', slugify('Int/Ext Painting') === 'int-ext-painting', slugify('Int/Ext Painting'));
проверка('слаг не начинается и не кончается дефисом', slugify('  AC Repair  ') === 'ac-repair', slugify('  AC Repair  '));

// --- профиль: обязательные поля ---
{
  const { ок, ошибки } = проверитьПрофиль({});
  проверка('пустой профиль не проходит', !ок);
  проверка('пустой профиль называет все недостающие поля', ошибки.length >= 6, `названо ${ошибки.length}`);
}

// --- профиль: число без источника ---
{
  const { ошибки } = проверитьПрофиль({ ...образец, tagline: 'Grew leads by 40%' });
  проверка('число-заявление в тексте профиля ловится', ошибки.some(о => о.includes('число без источника')));
}
проверка('процент опознаётся как заявление', числаБезИсточника('up 40% this year').length === 1);
проверка('обычный текст без чисел не даёт ложных находок', числаБезИсточника('Heating and cooling for homes').length === 0);

// --- профиль: факт без источника ---
{
  const { ошибки } = проверитьПрофиль({ ...образец, facts: [{ claim: 'Best in town' }] });
  проверка('факт без источника не проходит', ошибки.some(о => о.includes('факт без источника')));
}

// --- профиль: две услуги с одинаковым адресом ---
{
  // «AC Repair» и «AC-Repair» дают один слаг ac-repair. Пара выбрана не
  // наугад: первая попытка написать эту проверку взяла «AC Repair» и
  // «A/C repair», а они как раз НЕ сталкиваются (косая черта разделяет слова,
  // выходит a-c-repair). Проверка падала на верном коде — ровно тот случай,
  // когда врёт детектор, а не то, что он проверяет.
  const { ошибки } = проверитьПрофиль({ ...образец, services: ['AC Repair', 'AC-Repair'] });
  проверка('две услуги с одним адресом ловятся', ошибки.some(о => о.includes('один адрес')));
  const чистый = проверитьПрофиль({ ...образец, services: ['AC Repair', 'A/C repair'] });
  проверка('похожие, но разные адреса ложной находки не дают',
    !чистый.ошибки.some(о => о.includes('один адрес')));
}

// --- профиль: образец должен быть валиден ---
{
  const { ок, ошибки } = проверитьПрофиль(образец);
  проверка('образец профиля проходит проверку', ок, ошибки.join('; '));
}

// --- план страниц ---
{
  const профиль = {
    ...образец,
    services: образец.services.map(у => ({ ...у, slug: slugify(у.name) })),
    cities: образец.cities.map(г => ({ ...г, slug: slugify(г.name) })),
  };
  const { страницы, находки } = собратьПлан(профиль);

  проверка('план не пустой', страницы.length > 0);
  проверка('в плане есть главная', страницы.some(с => с.путь === '/'));
  проверка('в плане есть страница на каждую услугу',
    профиль.services.every(у => страницы.some(с => с.путь === `/services/${у.slug}`)));
  проверка('в плане есть страница на каждый город',
    профиль.cities.every(г => страницы.some(с => с.путь === `/areas/${г.slug}`)));

  const длинныеЗаголовки = страницы.filter(с => с.заголовок.length > ПРЕДЕЛ_ЗАГОЛОВКА);
  проверка(`заголовки не длиннее ${ПРЕДЕЛ_ЗАГОЛОВКА}`, длинныеЗаголовки.length === 0,
    длинныеЗаголовки.map(с => с.путь).join(', '));

  const длинныеОписания = страницы.filter(с => с.описание.length > ПРЕДЕЛ_ОПИСАНИЯ);
  проверка(`описания не длиннее ${ПРЕДЕЛ_ОПИСАНИЯ}`, длинныеОписания.length === 0,
    длинныеОписания.map(с => с.путь).join(', '));

  const заголовки = страницы.map(с => с.заголовок);
  проверка('одинаковых заголовков нет', new Set(заголовки).size === заголовки.length);

  const адреса = страницы.map(с => с.путь);
  проверка('одинаковых адресов нет', new Set(адреса).size === адреса.length);

  проверка('на маленьком профиле находок нет', находки.length === 0, находки.join('; '));
}

// --- порог тонких страниц ---
{
  const много = {
    ...образец,
    services: Array.from({ length: 8 }, (_, и) => ({ name: `Service ${и + 1}`, slug: `service-${и + 1}` })),
    cities: Array.from({ length: 9 }, (_, и) => ({ name: `City ${и + 1}`, slug: `city-${и + 1}` })),
  };
  const { находки, отложенныеСвязки } = собратьПлан(много);
  проверка(`перемножение выше порога ${ПОРОГ_ТОНКИХ} останавливается`, отложенныеСвязки.length > 0);
  проверка('порог объясняется человеку словами', находки.some(н => н.includes('порог')));
}

// --- стадии ---
проверка('стадий ровно семь', СТАДИИ.length === 7, `их ${СТАДИИ.length}`);
проверка('номера стадий идут подряд с нуля', СТАДИИ.every((с, и) => с.номер === и));
проверка('у каждой стадии есть режим и состояние', СТАДИИ.every(с => с.режим && с.состояние));
проверка('у каждой незакрытой стадии сказано, почему',
  СТАДИИ.filter(с => с.состояние === 'нет').every(с => с.почемуНет));

{
  // Стадия, требующая доступа, обязана остановиться, когда доступа нет.
  const безДоступов = { access: {} };
  const отчёт = СТАДИИ.find(с => с.id === 'report');
  проверка('стадия отчёта без доступов останавливается', преградыСтадии(отчёт, безДоступов).length > 0);

  const замер = СТАДИИ.find(с => с.id === 'baseline');
  проверка('замер выполним без единого доступа, если сайт есть',
    преградыСтадии(замер, { access: {}, site: 'https://example.com' }).length === 0);
  проверка('замер без сайта останавливается и говорит почему',
    преградыСтадии(замер, безДоступов).some(п => п.includes('нет сайта')));
}

// --- пути для замера: ключевые и пробники не должны пересекаться ---
{
  const профиль = {
    ...образец,
    site: 'https://example.com',
    services: образец.services.map(у => ({ ...у, slug: slugify(у.name) })),
    cities: образец.cities.map(г => ({ ...г, slug: slugify(г.name) })),
  };
  const { ключевые, пробники } = путиДляЗамера(профиль);
  const пересечение = ключевые.filter(п => пробники.includes(п));
  проверка('ключевые и пробники не пересекаются', пересечение.length === 0, пересечение.join(', '));
  проверка('в замере нет повторов',
    new Set([...ключевые, ...пробники]).size === ключевые.length + пробники.length);
  проверка('ключевые начинаются с главной', ключевые[0] === '/');
  проверка('пробники берутся из услуг или зон',
    пробники.every(п => п.startsWith('/services/') || п.startsWith('/areas/')));
}

// --- справочник доступов ---
проверка('у каждого доступа есть имя, группа и кто выдаёт',
  Object.values(ДОСТУПЫ).every(д => д.имя && д.группа && д.выдаёт));
проверка('у каждого доступа сказано, зачем он',
  Object.values(ДОСТУПЫ).every(д => typeof д.зачем === 'string' && д.зачем.length > 20));
проверка('номера блокируемых стадий существуют',
  Object.values(ДОСТУПЫ).every(д => д.стадии.every(н => СТАДИИ.some(с => с.номер === н))));
проверка('DNS домена есть в справочнике', Boolean(ДОСТУПЫ.domainDns),
  'без него не подтвердить Search Console и не завести почту');
проверка('хостинг есть в справочнике', Boolean(ДОСТУПЫ.hosting));
проверка('Railway и Hostinger известны как хостинги',
  Boolean(ХОСТИНГИ.railway) && Boolean(ХОСТИНГИ.hostinger));
проверка('у каждого хостинга сказано, что просить',
  Object.values(ХОСТИНГИ).every(х => х.имя && х.просить));

// --- профиль с неизвестным доступом не проходит ---
{
  const { ошибки } = проверитьПрофиль({ ...образец, access: { выдуманныйДоступ: true } });
  проверка('опечатка в названии доступа ловится',
    ошибки.some(о => о.includes('неизвестный доступ')));
}
{
  const { ошибки } = проверитьПрофиль({ ...образец, hosting: 'нетакогохостинга' });
  проверка('неизвестный хостинг ловится', ошибки.some(о => о.includes('неизвестный хостинг')));
}

// --- счёт доступов ---
{
  const { открыто, всего: сколько } = счётДоступов(castells);
  проверка('у Castells открыты только свои доступы', открыто === 2, `открыто ${открыто}`);
  проверка('счёт доступов считает весь справочник', сколько === Object.keys(ДОСТУПЫ).length);
  проверка('нехватка перечисляет ровно закрытые',
    нехваткаДоступов(castells).length === сколько - открыто);
}

// --- ежемесячный отчёт ---
проверка('в отчёте есть обязательные разделы', РАЗДЕЛЫ.some(р => р.обязателен));
проверка('у каждого раздела отчёта сказано, что в нём',
  РАЗДЕЛЫ.every(р => р.имя && р.что));
{
  const пустой = готовностьОтчёта({ access: {} });
  проверка('без доступов отчёт отправлять нельзя', !пустой.можноОтправлять);
  проверка('и сказано почему', Boolean(пустой.почемуНельзя));
}
{
  // Отчёт, где наполнены только «что сделали» и «что дальше», отправлять
  // нельзя: он не отвечает на вопрос клиента «что мне это дало».
  const толькоОНас = готовностьОтчёта({ access: { siteAdmin: true } });
  проверка('отчёт только о своей работе не считается отчётом',
    !толькоОНас.можноОтправлять && толькоОНас.почемуНельзя.includes('что мне это дало'));
}
{
  const сДанными = готовностьОтчёта({ access: { siteAdmin: true, searchConsole: true, analytics: true } });
  проверка('с поиском и счётчиком отчёт отправлять можно', сДанными.можноОтправлять);
}
{
  const до = следующийОтчёт(new Date(Date.UTC(2026, 7, 1)));
  const после = следующийОтчёт(new Date(Date.UTC(2026, 7, 20)));
  проверка('до дня отчёта — этот месяц', до.getUTCMonth() === 7 && до.getUTCDate() === ДЕНЬ_ОТЧЁТА);
  проверка('после дня отчёта — следующий месяц', после.getUTCMonth() === 8);
}

// --- профиль Castells должен быть валиден ---
{
  const { ок, ошибки } = проверитьПрофиль(castells);
  проверка('профиль Castells проходит проверку', ок, ошибки.join('; '));
}

// --- флаг «исполняется» не должен разойтись с настоящими исполнителями ---
{
  const поФлагу = СТАДИИ.filter(с => с.исполняется).map(с => с.id).sort();
  const поКоду = Object.keys(ИСПОЛНИТЕЛИ).sort();
  проверка('флаг исполняется совпадает с настоящими исполнителями',
    поФлагу.join(',') === поКоду.join(','), `флаг: ${поФлагу}; код: ${поКоду}`);
}

// --- пульт ---
{
  const проекты = await собратьПроекты();
  проверка('пульт видит хотя бы один проект', проекты.length > 0);
  const html = страница(проекты, '2026-08-29 00:00 UTC');

  проверка('у пульта есть заголовок страницы', html.includes('<title>'));
  проверка('пульт красит и светлую, и тёмную тему',
    html.includes('prefers-color-scheme: dark') && html.includes('[data-theme="dark"]'));
  проверка('у body задан свой фон', /body\{[^}]*background:var\(--ground\)/.test(html));
  проверка('в пульте нет незаполненных подстановок',
    !html.includes('undefined') && !html.includes('[object Object]') && !html.includes('NaN'));
  проверка('пульт называет каждую стадию', СТАДИИ.every(с => html.includes(с.имя)));
  проверка('пульт называет каждый доступ',
    Object.values(ДОСТУПЫ).every(д => html.includes(д.имя)));
  проверка('пульт показывает раздел про отчёт', html.includes('Ежемесячный отчёт'));
  проверка('широкие таблицы прокручиваются сами', html.includes('overflow-x:auto'));

  // Экранирование: в профиле лежит название компании, а не проверенный HTML.
  const опасный = [{
    id: 'x', профиль: { ...castells, name: '<img src=x onerror=alert(1)>' },
    проверка: { ок: true, ошибки: [] },
    стадии: [], доступы: { открыто: 0, всего: 12 }, нехватка: [],
    отчёт: { разделы: [], наполнятся: 0, всего: 7, можноОтправлять: false, почемуНельзя: 'нет' },
  }];
  проверка('название проекта экранируется',
    !страница(опасный, 'сейчас').includes('<img src=x'));
}

console.log(`\n${всего - упало}/${всего} проверок пройдено`);
process.exit(упало ? 1 : 0);
