/*
  Стадия 2 — структура страниц. Из профиля клиента собирается план: какие
  адреса должны существовать, с какими заголовками и описаниями.

  Это самая сильная наша часть, и не на словах: на собственном сайте этим
  способом собрано 123 страницы, и они живут на проде. Здесь тот же приём,
  но входные данные — профиль клиента, а не наши константы.

  ЧЕГО ЭТОТ ФАЙЛ НАМЕРЕННО НЕ ДЕЛАЕТ: не пишет тексты. План — это скелет
  (адрес, заголовок, описание, что должно быть на странице). Мясо пишет
  стадия 3, и там правило другое: без факта из профиля страница не пишется.

  ПРО «УСЛУГА × ГОРОД». Перемножение услуг на города даёт много страниц
  быстро, и именно так делают программатик-SEO. Так же легко получить триста
  одинаковых страниц, отличающихся одним словом, — и это ровно то, за что
  поиск наказывает. Поэтому здесь стоит порог: если перемножение даёт больше
  ПОРОГ_ТОНКИХ страниц, план это помечает и требует решения человека, а не
  молча генерирует.
*/

import { slugify } from './profile.mjs';

/** Длина заголовка, после которой поиск его обрезает. */
export const ПРЕДЕЛ_ЗАГОЛОВКА = 60;

/**
 * Длина описания. 165 — не выдумка, это наш собственный урок: 27 августа
 * выяснилось, что самопроверка длины описаний смотрела лишь на четверть
 * сайта, и под ней пряталось 43 длинных описания.
 */
export const ПРЕДЕЛ_ОПИСАНИЯ = 165;

/**
 * Сколько страниц «услуга × город» мы готовы сделать, не задав вопрос
 * человеку. Порог низкий сознательно: лучше спросить, чем наплодить тонких
 * страниц, которые потом придётся удалять.
 */
export const ПОРОГ_ТОНКИХ = 40;

/** Обрезает по границе слова, чтобы не рвать слово посередине. */
const подрезать = (текст, предел) => {
  if (текст.length <= предел) return текст;
  const край = текст.slice(0, предел);
  const пробел = край.lastIndexOf(' ');
  return (пробел > предел * 0.6 ? край.slice(0, пробел) : край).trim();
};

/**
 * Собирает план страниц из профиля.
 *
 * Возвращает { страницы, находки, тонкие } — где находки это то, что человек
 * обязан увидеть до публикации.
 */
export function собратьПлан(профиль) {
  const страницы = [];
  const находки = [];
  const имя = профиль.name;
  const услуги = профиль.services || [];
  const города = профиль.cities || [];

  const добавить = (путь, заголовок, описание, зачем) =>
    страницы.push({ путь, заголовок, описание, зачем });

  // --- Главная ---
  добавить(
    '/',
    подрезать(`${имя} | ${профиль.tagline || 'Services'}`, ПРЕДЕЛ_ЗАГОЛОВКА),
    подрезать(профиль.about || `${имя} serves ${города.map(г => г.name).join(', ')}.`, ПРЕДЕЛ_ОПИСАНИЯ),
    'вход, кто мы и что делаем',
  );

  // --- Хаб услуг и страница на каждую услугу ---
  if (услуги.length) {
    добавить('/services', подрезать(`Services | ${имя}`, ПРЕДЕЛ_ЗАГОЛОВКА),
      подрезать(`What ${имя} does: ${услуги.map(у => у.name).join(', ')}.`, ПРЕДЕЛ_ОПИСАНИЯ),
      'хаб, ведёт на все услуги');
  }
  for (const услуга of услуги) {
    добавить(
      `/services/${услуга.slug}`,
      подрезать(`${услуга.name} | ${имя}`, ПРЕДЕЛ_ЗАГОЛОВКА),
      подрезать(`${услуга.name} by ${имя}. ${услуга.description || ''}`.trim(), ПРЕДЕЛ_ОПИСАНИЯ),
      'что это за услуга, что входит, что стоит',
    );
  }

  // --- Страница на каждый город обслуживания ---
  for (const город of города) {
    добавить(
      `/areas/${город.slug}`,
      подрезать(`${имя} in ${город.name}`, ПРЕДЕЛ_ЗАГОЛОВКА),
      подрезать(`${имя} serves ${город.name}${город.state ? `, ${город.state}` : ''}.`, ПРЕДЕЛ_ОПИСАНИЯ),
      'зона обслуживания, местные приметы',
    );
  }

  // --- Услуга × город: программатик, и здесь же порог ---
  const тонкие = [];
  const пар = услуги.length * города.length;
  if (пар > 0) {
    for (const услуга of услуги) {
      for (const город of города) {
        const путь = `/services/${услуга.slug}/${город.slug}`;
        тонкие.push({
          путь,
          заголовок: подрезать(`${услуга.name} in ${город.name} | ${имя}`, ПРЕДЕЛ_ЗАГОЛОВКА),
          описание: подрезать(`${услуга.name} in ${город.name}${город.state ? `, ${город.state}` : ''} by ${имя}.`, ПРЕДЕЛ_ОПИСАНИЯ),
          зачем: 'связка услуга и город',
        });
      }
    }
  }

  if (пар > ПОРОГ_ТОНКИХ) {
    находки.push(
      `связок «услуга × город» получилось ${пар} (порог ${ПОРОГ_ТОНКИХ}). ` +
      `Столько страниц нельзя наполнить разным содержанием, а одинаковые ` +
      `страницы поиск не любит. Решение человека: сузить список городов, ` +
      `сузить услуги, или писать связки порциями по мере появления фактов.`,
    );
  } else {
    страницы.push(...тонкие);
  }

  // --- Обязательные страницы доверия ---
  добавить('/contact', подрезать(`Contact ${имя}`, ПРЕДЕЛ_ЗАГОЛОВКА),
    подрезать(`Get in touch with ${имя}.`, ПРЕДЕЛ_ОПИСАНИЯ), 'как связаться, адрес и телефон');
  добавить('/about', подрезать(`About ${имя}`, ПРЕДЕЛ_ЗАГОЛОВКА),
    подрезать(профиль.about || `About ${имя}.`, ПРЕДЕЛ_ОПИСАНИЯ), 'кто мы, чем докажем');

  // --- Проверки плана: то же, чему научил собственный сайт ---
  const поЗаголовку = new Map();
  for (const с of страницы) {
    if (с.заголовок.length > ПРЕДЕЛ_ЗАГОЛОВКА) {
      находки.push(`заголовок длиннее ${ПРЕДЕЛ_ЗАГОЛОВКА}: ${с.путь}`);
    }
    if (с.описание.length > ПРЕДЕЛ_ОПИСАНИЯ) {
      находки.push(`описание длиннее ${ПРЕДЕЛ_ОПИСАНИЯ}: ${с.путь}`);
    }
    if (!поЗаголовку.has(с.заголовок)) поЗаголовку.set(с.заголовок, []);
    поЗаголовку.get(с.заголовок).push(с.путь);
  }
  for (const [заголовок, пути] of поЗаголовку) {
    if (пути.length > 1) {
      находки.push(`одинаковый заголовок у ${пути.length} страниц («${заголовок}»): ${пути.join(', ')}`);
    }
  }

  const адреса = страницы.map(с => с.путь);
  const дубли = адреса.filter((а, и) => адреса.indexOf(а) !== и);
  for (const а of new Set(дубли)) находки.push(`адрес встречается дважды: ${а}`);

  return { страницы, находки, отложенныеСвязки: пар > ПОРОГ_ТОНКИХ ? тонкие : [] };
}

/**
 * Какие адреса отдать замеру (стадия 0): ключевые страницы и пробники.
 *
 * Вынесено сюда из оркестратора, чтобы это можно было проверить тестом. Первая
 * версия жила прямо в оркестраторе и содержала ошибку: пробники набирались из
 * всего плана, а ключевые — из его начала, и страницы услуг попадали в оба
 * списка. На прогоне по Castells шесть адресов проверялись дважды — прибор
 * тратил половину запросов впустую и печатал каждую находку по два раза.
 */
export function путиДляЗамера(профиль, { ключевых = 7, пробников = 6 } = {}) {
  const { страницы } = собратьПлан(профиль);
  const ключевые = страницы.slice(0, ключевых).map(с => с.путь);
  const взятые = new Set(ключевые);

  const пробники = страницы
    .map(с => с.путь)
    .filter(путь => !взятые.has(путь))
    .filter(путь => путь.startsWith('/services/') || путь.startsWith('/areas/'))
    .slice(0, пробников);

  return { ключевые, пробники };
}

export { slugify };
