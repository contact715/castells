/** Стадия по её строковому имени. */
export const стадия = id => СТАДИИ.find(с => с.id === id);

/**
 * Что мешает стадии выполниться у конкретного клиента.
 * Возвращает список причин; пустой список означает «выполнима».
 */
export function преградыСтадии(с, профиль) {
  const преграды = [];
  if (с.состояние === 'нет') преграды.push(`инструмента нет: ${с.почемуНет || 'не написан'}`);

  // Стадии, которые смотрят на живой сайт, без сайта не выполняются. Это не
  // поломка: у нового клиента сайта может ещё не быть, и это нормальный ход
  // работы — сначала строим, потом замеряем.
  if (с.требуетСайт && !профиль?.site) {
    преграды.push('у клиента ещё нет сайта — замерять нечего');
  }

  const доступы = профиль?.access || {};
  for (const нужен of с.требуетДоступ) {
    if (!доступы[нужен]) преграды.push(`нет доступа: ${нужен}`);
  }
  return преграды;
}
