#!/usr/bin/env node
/*
  Оркестратор цикла SEO по одному клиенту.

  Запуск:
    node services/seo/run.mjs <id-клиента>
    node services/seo/run.mjs <id-клиента> --stage pages
    node services/seo/run.mjs --list

  Что делает: читает профиль клиента, проверяет его, проходит семь стадий и
  говорит по каждой — сделано, заблокировано или ждёт человека. Ничего не
  публикует: публикация это отдельное действие с отдельным подтверждением.

  ПОЧЕМУ ОН НЕ «ДЕЛАЕТ ВСЁ САМ». Соблазн написать «прогнал команду — клиент
  готов» большой, и такой инструмент выглядел бы внушительнее. Но три из семи
  стадий сегодня физически невыполнимы без доступов и платных данных, а
  четвёртая не должна выполняться машиной вовсе. Инструмент, который делает
  вид, что отработал, хуже отсутствия инструмента: по его зелёному отчёту
  принимают решения, а работа не сделана.

  Поэтому оркестратор честный: он показывает ровно то, что можно сделать
  сегодня, и называет по имени каждое препятствие.
*/

import { readdir } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { проверитьПрофиль, разобратьПрофиль, CMS } from './lib/profile.mjs';
import { собратьПлан } from './lib/plan.mjs';
import { СТАДИИ, преградыСтадии, РЕЖИМ } from './lib/stages.mjs';

const выполнить = promisify(execFile);

const КОРЕНЬ = dirname(fileURLToPath(import.meta.url));
const ПАПКА_КЛИЕНТОВ = join(КОРЕНЬ, 'clients');

/** Список заведённых клиентов. Файлы с подчёркиванием — образцы, не клиенты. */
async function перечислитьКлиентов() {
  const файлы = await readdir(ПАПКА_КЛИЕНТОВ);
  return файлы.filter(ф => ф.endsWith('.mjs') && !ф.startsWith('_')).map(ф => ф.replace(/\.mjs$/, ''));
}

async function загрузитьПрофиль(id) {
  const модуль = await import(join(ПАПКА_КЛИЕНТОВ, `${id}.mjs`));
  const профиль = модуль.default || модуль.профиль;
  if (!профиль) throw new Error(`файл клиента ${id}.mjs не экспортирует профиль`);
  return профиль;
}

/**
 * Сколько ждём замер живого сайта, прежде чем прекратить. Замер ходит по
 * десятку адресов с повторами; если сеть недоступна, без ограничения он висел
 * бы минутами и выглядел как зависший инструмент.
 */
const ПРЕДЕЛ_ЗАМЕРА_МС = 120000;

/** Стадии, которые сегодня умеют выполняться по-настоящему. */
const ИСПОЛНИТЕЛИ = {
  /**
   * Стадия 0 — замер живого сайта клиента.
   *
   * Не переписываем прибор заново: запускаем тот же scripts/seo-audit.mjs, что
   * работает в утренней смене, но подсовываем ему адреса клиента через
   * окружение. Иначе он проверял бы на чужом сайте НАШИ пути (/work,
   * /industries/hvac-systems) и объявил бы поломкой то, чего там и не должно
   * быть.
   */
  async baseline(профиль) {
    const план = собратьПлан(профиль);
    const ключевые = план.страницы.slice(0, 7).map(с => с.путь);
    const пробники = план.страницы
      .filter(с => с.путь.startsWith('/services/') || с.путь.startsWith('/areas/'))
      .slice(0, 6)
      .map(с => с.путь);

    const прибор = join(КОРЕНЬ, '..', '..', 'scripts', 'seo-audit.mjs');
    const строки = [`смотрим на ${профиль.site}`, `адресов в замере: ${ключевые.length + пробники.length}`];

    try {
      const { stdout } = await выполнить('node', [прибор], {
        timeout: ПРЕДЕЛ_ЗАМЕРА_МС,
        env: {
          ...process.env,
          SEO_AUDIT_SITE: профиль.site,
          SEO_AUDIT_PATHS: ключевые.join(','),
          SEO_AUDIT_SAMPLES: пробники.join(','),
        },
      });
      const итог = stdout.trim().split('\n').filter(Boolean);
      строки.push(...итог.slice(-12));
      return { строки, находки: [] };
    } catch (e) {
      // Прибор возвращает код 1, когда есть находки — это не сбой запуска, а
      // рабочий результат, и его надо показать, а не проглотить.
      const вывод = (e.stdout || '').trim();
      if (вывод) {
        строки.push(...вывод.split('\n').filter(Boolean).slice(-12));
        return { строки, находки: ['замер нашёл проблемы на сайте клиента, разбор выше'] };
      }
      строки.push(`замер не отработал: ${e.message}`);
      return { строки, находки: [`стадия 0 не дала результата: ${e.message}`] };
    }
  },

  /**
   * Стадия 2 — единственная, которая прямо здесь производит результат.
   * Остальные либо живут в других скриптах (0 и 4), либо заблокированы.
   */
  pages(профиль) {
    const { страницы, находки, отложенныеСвязки } = собратьПлан(профиль);
    const строки = [`страниц в плане: ${страницы.length}`];
    if (отложенныеСвязки.length) {
      строки.push(`связок «услуга × город» отложено: ${отложенныеСвязки.length} (см. находки)`);
    }
    for (const с of страницы.slice(0, 8)) строки.push(`  ${с.путь}  ${с.заголовок}`);
    if (страницы.length > 8) строки.push(`  … и ещё ${страницы.length - 8}`);
    return { строки, находки };
  },
};

async function печатьСтадии(с, профиль) {
  const преграды = преградыСтадии(с, профиль);
  const шапка = `${с.номер}. ${с.имя}`;

  if (преграды.length) {
    console.log(`\n  [ждёт]     ${шапка}`);
    for (const п of преграды) console.log(`             ↳ ${п}`);
    return { выполнена: false, находки: [] };
  }

  if (с.режим === РЕЖИМ.человек) {
    console.log(`\n  [человек]  ${шапка}`);
    console.log(`             ↳ машине здесь делать нечего по замыслу, не по недоделке`);
    return { выполнена: false, находки: [] };
  }

  const исполнитель = ИСПОЛНИТЕЛИ[с.id];
  if (!исполнитель) {
    console.log(`\n  [снаружи]  ${шапка}`);
    console.log(`             ↳ выполняется отдельно: ${с.инструмент}`);
    return { выполнена: false, находки: [] };
  }

  const { строки, находки } = await исполнитель(профиль);
  console.log(`\n  [сделано]  ${шапка}${с.режим === РЕЖИМ.проверка ? '  (нужна проверка человеком)' : ''}`);
  for (const строка of строки) console.log(`             ${строка}`);
  return { выполнена: true, находки };
}

async function главная() {
  const аргументы = process.argv.slice(2);

  if (аргументы.includes('--list') || аргументы.length === 0) {
    const клиенты = await перечислитьКлиентов();
    console.log('Клиенты в проекте:');
    if (!клиенты.length) {
      console.log('  пока ни одного. Образец профиля: services/seo/clients/_template.mjs');
    }
    for (const к of клиенты) console.log(`  ${к}`);
    console.log('\nЗапуск: node services/seo/run.mjs <id-клиента>');
    return 0;
  }

  const id = аргументы[0];
  let сырой;
  try {
    сырой = await загрузитьПрофиль(id);
  } catch (e) {
    console.error(`Не удалось прочитать профиль «${id}»: ${e.message}`);
    return 1;
  }

  const { ок, ошибки, предупреждения } = проверитьПрофиль(сырой);
  const профиль = разобратьПрофиль(сырой);

  console.log(`\nЦикл SEO — ${профиль.name}`);
  console.log('─'.repeat(60));

  if (ошибки.length) {
    console.log('\nПрофиль не прошёл проверку:');
    for (const о of ошибки) console.log(`  ✗ ${о}`);
    console.log('\nПока профиль не исправлен, стадии не запускаются: работать с');
    console.log('неверными данными о клиенте хуже, чем не работать вовсе.');
    return 1;
  }

  const публикация = CMS[профиль.cms];
  console.log(`\nСайт: ${профиль.site || 'ещё нет'}`);
  console.log(`Где лежит: ${профиль.cms} — публикация ${публикация.публикация} (${публикация.примечание})`);
  console.log(`Услуг: ${профиль.services.length}, городов: ${профиль.cities.length}`);

  if (предупреждения.length) {
    console.log('\nПредупреждения:');
    for (const п of предупреждения) console.log(`  • ${п}`);
  }

  console.log('\nСтадии:');
  const всеНаходки = [];
  let сделано = 0;
  for (const с of СТАДИИ) {
    const итог = await печатьСтадии(с, профиль);
    if (итог.выполнена) сделано++;
    всеНаходки.push(...итог.находки);
  }

  console.log('\n' + '─'.repeat(60));
  console.log(`Выполнено здесь: ${сделано} из ${СТАДИИ.length} стадий.`);

  if (всеНаходки.length) {
    console.log('\nНаходки, требующие решения человека:');
    for (const н of всеНаходки) console.log(`  ! ${н}`);
  }

  console.log('\nЧто это значит: цикл не закрыт и закрыт быть не может, пока');
  console.log('открыты доступы и не куплены данные о запросах. Это состояние');
  console.log('дел, а не сбой инструмента.');

  return ок ? 0 : 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  главная().then(код => process.exit(код)).catch(e => {
    console.error(e);
    process.exit(1);
  });
}
