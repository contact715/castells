/**
 * Готовность отчёта по конкретному проекту: какие разделы наполнятся, какие
 * встанут и почему.
 *
 * Отдельно считаем, можно ли вообще отправлять отчёт: если ни один
 * обязательный раздел не наполняется, отчёт получится письмом «мы работали»,
 * и отправлять такое хуже, чем не отправлять.
 */
export function готовностьОтчёта(профиль) {
  const есть = профиль?.access || {};

  // Раздел наполняется, только когда сошлось И то, и другое: есть доступ к
  // данным И подключена услуга, которая эти данные производит. Без второго
  // условия отчёт обещал бы раздел «Реклама» клиенту, которому мы рекламу не
  // ведём, — и выглядел бы как недоработка вместо честной картины.
  const отУслуг = new Set(разделыОтУслуг(профиль));

  /*
    Для разделов с `доступыОтУслуг` список нужных доступов собирается из тех
    подключённых услуг, которые этот раздел наполняют. Иначе раздел был бы
    привязан к одному каналу навсегда — см. разбор у раздела «Реклама».
  */
  const подключённые = услугиПроекта(профиль).filter(у => у.состояние !== 'обсуждаем');
  const доступыРаздела = р => {
    if (!р.доступыОтУслуг) return р.нужныДоступы;
    const из = new Set();
    for (const у of подключённые) {
      if (!у.вОтчёт?.includes(р.id)) continue;
      for (const д of у.доступы || []) из.add(д);
    }
    return [...из];
  };

  const разделы = РАЗДЕЛЫ.map(р => {
    const нужны = доступыРаздела(р);
    const нет = нужны.filter(д => !есть[д]);
    const услугаЕсть = р.нужныДоступы.length === 0 && !р.доступыОтУслуг
      ? true
      : отУслуг.has(р.id);
    const мешает = нет.map(д => ДОСТУПЫ[д]?.имя || д);
    if (!услугаЕсть) мешает.push('услуга не подключена');
    return {
      ...р,
      нужныДоступы: нужны,
      наполнится: нет.length === 0 && услугаЕсть,
      мешает,
    };
  });

  const наполнятся = разделы.filter(р => р.наполнится);

  /*
    Отчёт годится к отправке, когда наполнился хотя бы один раздел О
    РЕЗУЛЬТАТЕ — обращения, поиск, посещения, местный поиск, реклама. «Что
    сделали» и «что дальше» мы можем написать всегда, но отчёт из одних них
    не отвечает на вопрос клиента «что мне это дало».

    Проверка исправлена 29 августа. Раньше она смотрела только на
    ОБЯЗАТЕЛЬНЫЕ разделы, и на HP Tinting соврала: у них наполняется «Местный
    поиск» — настоящий результат для клиента, — но раздел не помечен
    обязательным, в подсчёт не попадал, и вердикт говорил «только о нашей
    работе». Обязательность и «про результат» — разные признаки, и путать их
    нельзя.
  */
  const оРезультате = наполнятся.filter(р => р.оРезультате);

  return {
    разделы,
    наполнятся: наполнятся.length,
    всего: разделы.length,
    можноОтправлять: оРезультате.length > 0,
    почемуНельзя: оРезультате.length > 0
      ? null
      : наполнятся.length > 0
        ? 'наполняются только разделы о нашей работе; на вопрос «что мне это дало» отчёт не отвечает'
        : 'не наполняется ни один раздел',
  };
}

/** Дата следующего отчёта от заданного дня. */
export function следующийОтчёт(от = new Date()) {
  const год = от.getUTCFullYear();
  const месяц = от.getUTCMonth();
  const вЭтомМесяце = new Date(Date.UTC(год, месяц, ДЕНЬ_ОТЧЁТА));
  return от.getUTCDate() < ДЕНЬ_ОТЧЁТА
    ? вЭтомМесяце
    : new Date(Date.UTC(год, месяц + 1, ДЕНЬ_ОТЧЁТА));
}
