/**
 * Каких доступов не хватает и что из-за этого встаёт.
 * Возвращает список записей, пригодный и для отчёта, и для пульта.
 */
export function нехваткаДоступов(профиль) {
  const есть = профиль?.access || {};
  return Object.entries(ДОСТУПЫ)
    .filter(([ключ]) => !есть[ключ])
    .map(([ключ, д]) => ({
      ключ,
      имя: д.имя,
      группа: д.группа,
      зачем: д.зачем,
      выдаёт: д.выдаёт,
      блокируетСтадии: д.стадии,
    }));
}

/** Сколько доступов открыто из всех известных. */
export function счётДоступов(профиль) {
  const есть = профиль?.access || {};
  const всего = Object.keys(ДОСТУПЫ).length;
  const открыто = Object.keys(ДОСТУПЫ).filter(к => есть[к]).length;
  return { открыто, всего };
}
