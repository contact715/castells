/*
  Правила счётчика посещений. Чистые функции: ни сети, ни базы, ни времени
  «изнутри» — всё приходит доводами.

  ЗАЧЕМ СВОЙ СЧЁТЧИК, А НЕ ГОТОВЫЙ. Umami и Plausible ставятся сами и дают
  готовый экран аналитики, но каждый из них — ЕЩЁ ОДИН сервис на Railway со
  СВОЕЙ базой: расходы удваиваются, а данные ложатся в чужую схему, из которой
  ежемесячный отчёт всё равно пришлось бы тянуть через их API и сводить с
  нашими стадиями. Здесь нужен не экран аналитики, а две цифры в отчёт
  клиенту. Приём события — это маршрут, таблица и скрипт на два килобайта.

  ПРИВАТНОСТЬ НЕ ПРИЯТНОЕ ДОПОЛНЕНИЕ, А УСТРОЙСТВО. Мы не храним ни IP, ни
  cookie, ни идентификатор, живущий дольше суток:

    посетитель = хеш(соль этих суток + адрес + браузер + проект)

  Соль меняется каждые сутки, поэтому связать вчерашнего посетителя с
  сегодняшним нельзя даже нам. Обратно из хеша адрес не достать. Это тот же
  приём, что у Plausible, и он снимает необходимость в баннере про cookie —
  а баннер на сайте клиента стоит конверсии.
*/

import { createHash } from 'node:crypto';

/**
 * Домен без www и без порта, в нижнем регистре.
 *
 * Нужен в двух местах — при разборе адреса сайта из профиля и при разборе
 * заголовка Origin, — и оба должны нормализовать ОДИНАКОВО, иначе
 * «www.castells.media» из профиля не совпадёт с «castells.media» из браузера
 * и события молча полетят в корзину.
 */
export const домен = адрес => {
  if (!адрес) return '';
  const строка = String(адрес).trim();
  try {
    const u = new URL(строка.includes('://') ? строка : `https://${строка}`);
    return u.hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return '';
  }
};

/**
 * Отпечаток посетителя на сутки.
 *
 * Проект входит в хеш намеренно: один и тот же человек, зашедший на два наших
 * сайта, не должен получать один отпечаток — иначе счётчик стал бы средством
 * связывать посещения разных клиентов между собой.
 */
export const отпечаток = ({ соль, адрес, браузер, проект }) =>
  createHash('sha256')
    .update(`${соль}|${адрес || ''}|${браузер || ''}|${проект}`)
    .digest('hex')
    .slice(0, 32);

/**
 * Тип устройства по строке браузера. Три значения, больше не нужно: отчёт
 * отвечает на вопрос «с телефона или с компьютера», а не строит статистику
 * по моделям.
 */
export const устройство = браузер => {
  const с = String(браузер || '').toLowerCase();
  if (/ipad|tablet|playbook|silk/.test(с)) return 'планшет';
  if (/mobi|iphone|android.*mobile|phone/.test(с)) return 'телефон';
  return 'компьютер';
};

/**
 * Путь без параметров и без якоря: в отчёте нужна страница, а не метки.
 *
 * ПУТЬ РАСКОДИРУЕТСЯ. Браузер отдаёт `/услуги` как
 * `/%D1%83%D1%81%D0%BB%D1%83%D0%B3%D0%B8`, и без раскодирования в отчёте
 * клиента вместо названий страниц стояли бы проценты с цифрами. У клиентов с
 * латинскими адресами это незаметно, поэтому и ловится только проверкой.
 * Раскодирование обёрнуто: битая последовательность процентов роняет
 * decodeURIComponent, и одно кривое обращение уронило бы приём событий.
 */
export const путьСтраницы = адрес => {
  if (!адрес) return '/';
  try {
    const u = new URL(String(адрес).includes('://') ? адрес : `https://x${адрес}`);
    const p = u.pathname || '/';
    const чистый = p.length > 1 ? p.replace(/\/+$/, '') || '/' : '/';
    try { return decodeURIComponent(чистый); } catch { return чистый; }
  } catch {
    return '/';
  }
};

/**
 * Источник перехода: домен, откуда пришли. Свой же домен источником не
 * считается — иначе внутренние переходы выглядели бы как приведённый трафик.
 */
export const источник = (реферер, свойДомен) => {
  const д = домен(реферер);
  if (!д || д === домен(свойДомен)) return null;
  return д;
};

/**
 * Событие годится к записи? Возвращает причину отказа или null.
 *
 * Проверка отдельной функцией, а не внутри маршрута, потому что причина
 * отказа должна проверяться самопроверками без поднятия сервера.
 */
export const почемуНеПринять = ({ проект, путь }) => {
  if (!проект) return 'событие не относится ни к одному нашему сайту';
  if (!путь || путь.length > 512) return 'путь пустой или слишком длинный';
  return null;
};
