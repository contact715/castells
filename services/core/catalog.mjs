/**
 * Какие услуги подключены у проекта и в каком состоянии.
 *
 * Поле называется `engaged`, а не `services`, намеренно: `services` в профиле
 * уже занято — там услуги САМОГО КЛИЕНТА (ремонт кондиционеров, установка
 * отопления), из которых строятся страницы. Два разных смысла под одним
 * словом — это то, из-за чего потом полдня ищут, почему в плане страниц
 * оказалась «реклама в Meta».
 * Возвращает список записей с разобранной услугой — чтобы вызывающему не
 * приходилось лазить в справочник самому.
 */
export function услугиПроекта(профиль) {
  const подключено = профиль?.engaged || {};
  return Object.entries(подключено)
    .filter(([ключ]) => УСЛУГИ[ключ])
    .map(([ключ, состояние]) => ({
      ключ,
      состояние,
      ...УСЛУГИ[ключ],
      нехватка: УСЛУГИ[ключ].доступы.filter(д => !профиль?.access?.[д]),
    }));
}

/** Какие разделы отчёта наполняются подключёнными услугами. */
export function разделыОтУслуг(профиль) {
  const разделы = new Set();
  for (const у of услугиПроекта(профиль)) {
    if (у.состояние === 'обсуждаем') continue;
    for (const р of у.вОтчёт) разделы.add(р);
  }
  return [...разделы];
}
