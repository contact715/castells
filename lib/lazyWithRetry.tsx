import React from 'react';

/**
 * Ленивая загрузка куска сайта, переживающая выкатку новой версии.
 *
 * Проблема, пойманная на проде 22 августа 2026. Сайт грузит секции по
 * частям: пока человек не долистал до отзывов, их код не скачивается.
 * Имя файла содержит отпечаток содержимого, и после выкатки новой версии
 * старые файлы с домена пропадают.
 *
 * Значит у любого, кто держал вкладку открытой во время выкатки, при
 * докрутке до следующей секции запрос за её кодом отвечает 404, и секция
 * просто не появляется. В консоли это выглядело так:
 *   TrustSection-CWOx0J0G.js -> 404
 *   Industries-CHoBm_gP.js   -> 404
 *   Process-DdWE7kM0.js      -> 404
 * Сегодня было семь выкаток подряд, то есть окно поломки открывалось
 * семь раз.
 *
 * Лечение: не получилось скачать кусок — один раз перезагружаем страницу,
 * человек получает свежую версию и видит секцию. Метка о перезагрузке
 * живёт во вкладке, поэтому зациклиться нельзя: если и после обновления
 * файла нет (сеть лежит, а не выкатка), ошибка пробрасывается дальше, и
 * её ловит ErrorBoundary.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function lazyWithRetry<T extends React.ComponentType<any>>(
  factory: () => Promise<{ default: T }>
) {
  return React.lazy(async () => {
    try {
      return await factory();
    } catch (error) {
      const KEY = 'castells:chunk-reload-at';
      let last = 0;
      try {
        last = Number(window.sessionStorage.getItem(KEY) || 0);
      } catch {
        // приватный режим — хранилище недоступно, тогда просто пробуем один раз
      }

      const now = Date.now();
      // Минута — окно, за которое выкатка успевает доехать. Чаще не
      // перезагружаемся, иначе при лежащей сети получится вечный цикл.
      if (now - last > 60_000) {
        try {
          window.sessionStorage.setItem(KEY, String(now));
        } catch {
          // не смогли запомнить — всё равно перезагружаемся один раз
        }
        window.location.reload();
        // Пока браузер перезагружает страницу, отдаём пустоту вместо ошибки
        return { default: (() => null) as unknown as T };
      }

      throw error;
    }
  });
}
