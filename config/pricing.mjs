/** Суммы в долларах. Одно место, где их можно поменять. */
export const PRICE = {
  /** Один канал: Google, Meta или Yelp. В месяц. */
  monthlyOneChannel: 590,
  /** Несколько каналов плюс местное присутствие и отзывы. В месяц. */
  monthlySeveralChannels: 1490,
  /** Сайт или посадочная страница. Разовая работа, «от». */
  websiteFrom: 1750,
  /** Настройка CRM и дожима заявок. Разовая работа, «от». */
  crmSetupFrom: 1500,
};

/**
 * Формат американский: тысячи через запятую, без копеек. Вынесен функцией,
 * чтобы формат тоже был один: 1490 не должно где-то стать «1490», а где-то
 * «1,490».
 */
export const money = (сумма) => `$${сумма.toLocaleString('en-US')}`;

/** Готовые строки для вставки в текст. Ими пользуются обе стороны сайта. */
export const PRICES = {
  monthlyOneChannel: money(PRICE.monthlyOneChannel),
  monthlySeveralChannels: money(PRICE.monthlySeveralChannels),
  websiteFrom: money(PRICE.websiteFrom),
  crmSetupFrom: money(PRICE.crmSetupFrom),
};

/**
 * Оборот «от N» одной строкой. Отдельно, потому что в карточках он выводится
 * как значение цены, и раньше слово «from» было вписано внутрь строки цены —
 * из-за этого одно и то же число существовало в двух видах.
 */
export const FROM = {
  website: `from ${PRICES.websiteFrom}`,
  crmSetup: `from ${PRICES.crmSetupFrom}`,
};

/**
 * Готовое предложение о ценах для описаний страниц и текстов. Один раз
 * написанное, оно не разойдётся между страницей цен и файлом для нейросетей.
 */
export const PRICING_SENTENCE =
  `Monthly plans at ${PRICES.monthlyOneChannel} and ${PRICES.monthlySeveralChannels}, ` +
  `websites from ${PRICES.websiteFrom}, CRM setup from ${PRICES.crmSetupFrom}.`;
