#!/usr/bin/env node
/**
 * Замер живого сайта. Смотрит на прод, а не на код: код может быть правильным,
 * а на сервере лежать прошлая сборка — так у нас уже было.
 *
 * Что проверяет:
 *   1. отвечают ли ключевые страницы;
 *   2. нет ли страниц с одинаковым заголовком (для поиска это дубли);
 *   3. есть ли у каждой страницы описание и H1 прямо в HTML;
 *   4. живы ли все адреса из карты сайта;
 *   5. сколько весит и за сколько отдаётся главная.
 *
 * Запуск:
 *   node scripts/seo-audit.mjs
 *   node scripts/seo-audit.mjs --self-test
 *
 * Выход: 0 — всё чисто, 1 — есть находки. Годится для утренней задачи.
 */

import { fileURLToPath } from 'node:url';

const SITE = process.env.SEO_AUDIT_SITE || 'https://castells.media';
const TIMEOUT = 15000;

/** Страницы, которые обязаны работать и иметь свои теги. */
const КЛЮЧЕВЫЕ = ['/', '/work', '/services', '/pricing', '/about', '/contact', '/blog'];

/** Разделы, где страниц много и теги у них должны различаться. */
const ПРОБНИКИ = [
  '/services/web-development',
  '/services/meta-ads',
  '/industries/hvac-systems',
  '/industries/roofing-services',
  '/blog/1',
  '/blog/2',
];

const пауза = мс => new Promise(r => setTimeout(r, мс));

/**
 * Один запрос с повтором. Повтор нужен не для красоты: при серии запросов
 * подряд часть из них срывается на уровне соединения, и без повтора прибор
 * объявляет живую страницу мёртвой. Детектор, который врёт, хуже отсутствия
 * детектора — по его ложным находкам начинают чинить то, что не сломано.
 */
async function достать(путь, попыток = 3) {
  const url = путь.startsWith('http') ? путь : SITE + путь;
  let последняя = null;
  for (let попытка = 1; попытка <= попыток; попытка++) {
    const начало = Date.now();
    try {
      const ответ = await fetch(url, {
        signal: AbortSignal.timeout(TIMEOUT),
        headers: { 'User-Agent': 'castells-seo-audit', 'Accept-Encoding': 'identity' },
      });
      const текст = await ответ.text();
      return { url, код: ответ.status, html: текст, мс: Date.now() - начало, байт: текст.length };
    } catch (e) {
      последняя = e;
      if (попытка < попыток) await пауза(400 * попытка);
    }
  }
  return { url, код: 0, html: '', мс: 0, байт: 0, ошибка: последняя ? `${последняя.name}: ${последняя.message}` : 'неизвестно' };
}

const вынуть = (html, регулярка) => {
  const m = html.match(регулярка);
  return m ? m[1].trim() : null;
};
const заголовок = html => вынуть(html, /<title>([^<]*)<\/title>/i);
const описание = html => вынуть(html, /<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)["']/i);
const h1 = html => вынуть(html, /<h1[^>]*>([\s\S]*?)<\/h1>/i);

async function аудит() {
  const находки = [];
  const строки = [];

  строки.push(`Замер сайта ${SITE}`);
  строки.push('');

  // --- 1. ключевые страницы ---
  строки.push('Ключевые страницы');
  const собранные = [];
  for (const путь of [...КЛЮЧЕВЫЕ, ...ПРОБНИКИ]) {
    const r = await достать(путь);
    await пауза(120);
    собранные.push({ путь, ...r });
    const t = заголовок(r.html);
    const d = описание(r.html);
    const метка = r.код === 200 ? 'ок' : `КОД ${r.код}`;
    if (r.код !== 200) находки.push(`${путь} отвечает ${r.код || 'ничем'}${r.ошибка ? ` (${r.ошибка})` : ''}`);
    if (r.код === 200 && !d) находки.push(`${путь} без описания в HTML`);
    if (r.код === 200 && !h1(r.html)) находки.push(`${путь} без заголовка H1 в HTML`);
    if (КЛЮЧЕВЫЕ.includes(путь)) {
      строки.push(`  ${путь.padEnd(28)} ${метка.padEnd(9)} ${(t || 'без заголовка').slice(0, 58)}`);
    }
  }

  // --- 2. дубли заголовков ---
  строки.push('');
  строки.push('Одинаковые заголовки');
  const поЗаголовку = new Map();
  for (const с of собранные) {
    if (с.код !== 200) continue;
    const t = заголовок(с.html) || '(нет)';
    if (!поЗаголовку.has(t)) поЗаголовку.set(t, []);
    поЗаголовку.get(t).push(с.путь);
  }
  let дублей = 0;
  for (const [t, пути] of поЗаголовку) {
    if (пути.length > 1) {
      дублей += пути.length;
      строки.push(`  ${пути.length} страниц: ${t.slice(0, 48)}`);
      строки.push(`    ${пути.join(', ')}`);
      находки.push(`${пути.length} страниц с одним заголовком: ${пути.join(', ')}`);
    }
  }
  if (!дублей) строки.push('  дублей нет');

  // --- 3. карта сайта ---
  строки.push('');
  строки.push('Карта сайта');
  const карта = await достать('/sitemap.xml');
  if (карта.код !== 200) {
    строки.push(`  карта недоступна (${карта.код})`);
    находки.push('карта сайта недоступна');
  } else {
    const адреса = [...карта.html.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => m[1]);
    строки.push(`  адресов в карте: ${адреса.length}`);
    let битых = 0;
    for (const адрес of адреса) {
      const r = await достать(адрес);
      await пауза(120);
      if (r.код !== 200) {
        битых++;
        строки.push(`  битый: ${адрес} → ${r.код}`);
        находки.push(`адрес из карты сайта отвечает ${r.код}: ${адрес}`);
      }
    }
    if (!битых) строки.push('  все адреса отвечают 200');
  }

  // --- 4. скорость и вес главной ---
  строки.push('');
  строки.push('Главная');
  const замеры = [];
  for (let i = 0; i < 3; i++) замеры.push(await достать(`/?audit=${i}${Date.now()}`));
  const среднее = Math.round(замеры.reduce((s, r) => s + r.мс, 0) / замеры.length);
  const вес = Math.round(замеры[0].байт / 1024);
  строки.push(`  отдаётся за ${среднее} мс (среднее из трёх), весит ${вес} КБ`);
  if (среднее > 3000) находки.push(`главная отдаётся за ${среднее} мс, это долго`);

  // --- итог ---
  строки.push('');
  if (находки.length === 0) {
    строки.push('Находок нет.');
  } else {
    строки.push(`Находок: ${находки.length}`);
    находки.forEach((н, i) => строки.push(`  ${i + 1}. ${н}`));
  }

  console.log(строки.join('\n'));
  return находки.length;
}

/** Самопроверка: чистые функции разбора, без обращения к сети. */
function самопроверка() {
  const проверки = [];
  const тест = (имя, условие) => проверки.push({ имя, ок: !!условие });

  const html = `<html><head><title>Заголовок</title>
    <meta name="description" content="Описание страницы"></head>
    <body><h1>Главный заголовок</h1></body></html>`;

  тест('вынимает заголовок', заголовок(html) === 'Заголовок');
  тест('вынимает описание', описание(html) === 'Описание страницы');
  тест('вынимает H1', h1(html) === 'Главный заголовок');
  тест('нет заголовка — возвращает null', заголовок('<html></html>') === null);
  тест('нет описания — возвращает null', описание('<html></html>') === null);
  тест('описание в одинарных кавычках', описание(`<meta name='description' content='Текст'>`) === 'Текст');
  тест('H1 с вложенными тегами', h1('<h1>Текст <span>внутри</span></h1>').includes('внутри'));
  тест('адрес сайта задан', typeof SITE === 'string' && SITE.startsWith('http'));
  тест('ключевых страниц не меньше семи', КЛЮЧЕВЫЕ.length >= 7);
  // Function.length не считает параметры со значением по умолчанию,
  // поэтому смотрим на само тело функции.
  тест('у запроса есть повторы', /попыток/.test(достать.toString()));
  тест('пробники берут и услуги, и ниши',
    ПРОБНИКИ.some(p => p.startsWith('/services/')) && ПРОБНИКИ.some(p => p.startsWith('/industries/')));

  const упало = проверки.filter(p => !p.ок);
  проверки.forEach(p => console.log(`  ${p.ок ? 'ок  ' : 'СБОЙ'} ${p.имя}`));
  console.log(`\n  проверок: ${проверки.length}, сбоев: ${упало.length}`);
  return upalo(упало);
}
const upalo = список => список.length;

// Работа только при прямом запуске: импорт файла ничего не делает.
const этоЗапуск = process.argv[1] === fileURLToPath(import.meta.url);
if (этоЗапуск) {
  const режим = process.argv.includes('--self-test') ? самопроверка : аудит;
  Promise.resolve(режим()).then(находок => process.exit(находок > 0 ? 1 : 0));
}

export { заголовок, описание, h1, достать };
