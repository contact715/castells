/*
 * Самоуничтожающийся service worker.
 *
 * Когда-то на сайте был включён офлайн-режим, и у посетителей в браузере
 * остались его копии, зарегистрированные по адресу /sw.js. Офлайн-режим
 * выключили, файл пропал, и браузер начал получать вместо него HTML-страницу.
 * Обновить копию он не может (неверный тип содержимого), поэтому старая копия
 * живёт вечно и продолжает показывать человеку версию сайта годичной давности.
 *
 * Этот файл существует ровно для того, чтобы браузеру было что скачать вместо
 * старой копии. При активации он стирает все кэши, снимает собственную
 * регистрацию и перезагружает открытые вкладки, после чего исчезает сам.
 * Удалять его нельзя, пока у людей могут оставаться старые регистрации.
 */

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      try {
        const keys = await caches.keys();
        await Promise.all(keys.map((key) => caches.delete(key)));
      } catch (e) {
        // кэшей может не быть — это не ошибка
      }

      await self.registration.unregister();

      const clients = await self.clients.matchAll({ type: 'window' });
      clients.forEach((client) => {
        try {
          client.navigate(client.url);
        } catch (e) {
          // вкладка могла закрыться
        }
      });
    })()
  );
});

// Пока эта копия ещё активна, ничего не перехватываем: любой запрос идёт в сеть.
self.addEventListener('fetch', () => {});
